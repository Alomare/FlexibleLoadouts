-- Frame step

local state = {ready = false, screen = nil}

local function leave_screen()
    state.screen = nil
    visit.offers = nil
    ready.flash, ready.idle, advance.slot = nil, nil, nil
    -- The buttons stay where they are (the same screen object may come back); the next visit checks them first. A
    -- slot unhovered under its X is in the game's own "not hovered" state: nothing to undo.
    buttons.visit = buttons.visit + 1
    for _, b in pairs(buttons.slots) do b.unhovered = false end
    buttons.hovered, buttons.blocked, buttons.cleared, buttons.gates = nil, nil, nil, nil
    -- The same for the Leave Out buttons: a slot unhovered under one was redrawn by the game's own redraw, and the
    -- game redraws it again on its next hover change.
    toggles.visit = toggles.visit + 1
    for _, t in pairs(toggles.slots) do t.unhovered = false end
    toggles.hovered, toggles.blocked, toggles.changed, toggles.gates = nil, nil, nil, nil
    -- The pins and the reroll button the same way (the list is built again at its next opening).
    visit.items = nil
    pins.visit = pins.visit + 1
    pins.written, pins.ids, pins.pos, pins.vanilla, pins.scan, pins.restore = nil, nil, nil, nil, nil, nil
    pins.hovered, pins.blocked, pins.logged = nil, nil, nil
    dice.visit = dice.visit + 1
    dice.hovered, dice.blocked, dice.under.unhovered = nil, nil, false
    if dice.roll then
        note(string.format('Randomize Lineup: stopped after %d slot(s) (the screen left)', dice.roll.k))
        dice.roll = nil
    end
end

local function loadout_screen()
    if not read_into(buffers.global, native.base + L.stack, 8) then return nil end
    local stack = buf_pointer(buffers.global, 0)
    if not stack or not read_into(buffers.stack, stack, L.slot + 8) then return nil end
    if buf_u32(buffers.stack, 0) ~= LOADOUT_SCREEN then return nil end
    return buf_pointer(buffers.stack, L.slot)
end

local function step()
    if EXTRA.weapons then
        if key_pressed('f8') then destroy_kept() end
        service_weapons()
    end
    local pressed = EXTRA.clear and clear_key_pressed()
    if not state.screen and M.frames % IDLE_POLL ~= 0 then return end
    local screen = loadout_screen()
    if screen ~= state.screen then
        if state.screen then leave_screen() end
        state.screen = screen
    end
    if not screen or not read_into(buffers.head, screen + SCREEN.head, SCREEN.head_size) then return end
    local index = buf_u32(buffers.head, SCREEN.local_index)
    local category = buf_u32(buffers.head, SCREEN.category)
    if index <= 3 and (EXTRA.ready or EXTRA.advance or EXTRA.clear) and read_into(buffers.byte, screen + L.list_open, 1) then
        local list_open = buffers.byte[0] ~= 0
        if EXTRA.ready then service_ready(screen, list_open) end
        if EXTRA.advance then service_advance(screen, index, list_open, category) end
        if pressed then press_key(screen, index, list_open) end
        if EXTRA.buttons then service_buttons(screen, index, list_open) end
        if EXTRA.toggles then service_toggles(screen, list_open) end
        if EXTRA.pins then pins.service(screen) end
        if EXTRA.dice then
            dice.service(screen, index, list_open)
            dice.service_roll(screen, list_open)
        end
    end
end

