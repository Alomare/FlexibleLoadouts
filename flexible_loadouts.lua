local function i32(v) return v and (v >= 2147483648 and v - 4294967296 or v) end
local function u8_at(address) local b = read(address, 1); return b and b:byte(1) end
local function u32_at(address) return u32(read(address, 4)) end
local function f32(blob, offset)
    if not blob or #blob < offset + 4 then return nil end
    local v = ffi.new('float[1]')
    ffi.copy(v, blob:sub(offset + 1, offset + 4), 4)
    return tonumber(v[0])
end
local function pointer_at(address) return pointer(read(address, 8)) end

