-- Each button is a few pictures of the game's own widget kind, in memory the mod owns (zeroed, 16-byte aligned, never
-- freed: the game may keep pointers to a widget), made inside the slot's GUI context and attached under the slot
-- widget, so the game's widget tree places them every frame (resolution, UI scale, the screen's intro). The look: a
-- dark plate of the game's solid fill under the game's own red cross (content/ui/shared/misc/check_no_no_curve, which
-- the game itself tints red), or under two rotated bars of the fill when the cross is not loaded. It fades in and out
-- with the game's own fade helper. While an X is hovered its slot looks unhovered (the game's own unhovered state).
