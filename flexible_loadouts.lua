-- The layout, from the matched code

local code = nil  -- the signature engine
local L = {}      -- field name -> value (offsets) or rva (globals, functions)
local SCREEN, BLOCK = {}, {}

-- Checks the pieces fit together (the engine already made every field agree across signatures).
local function read_layout()
    for _, name in ipairs(REQUIRED) do
        if not code.found[name] then return false, string.format('code "%s" %s', name, code.missing[name] or 'not found') end
    end
    if #code.problems > 0 then return false, code.problems[1] end
    for k, v in pairs(code.values) do L[k] = v end
    local found = code.found
    -- The functions: the refresh the handler calls holds refresh_a/b.
    for _, part in ipairs({'refresh_a', 'refresh_b'}) do
        if found[part] < L.refresh or found[part] > L.refresh + 0x1000 then return false, part .. ' outside the refresh' end
    end
    -- The spans read each frame: the screen head (local index .. category), a loadout block (entries .. count).
    if L.category <= L.local_index or L.category - L.local_index > 0x1000 then return false, 'screen head layout' end
    SCREEN.head, SCREEN.head_size = L.local_index, L.category - L.local_index + 4
    SCREEN.local_index, SCREEN.category = 0, L.category - L.local_index
    SCREEN.blocks, SCREEN.block_size, SCREEN.list = L.block_base, L.block_stride, L.list
    BLOCK.entries, BLOCK.count = L.block_entries, L.block_count
    if BLOCK.count < BLOCK.entries + BLOCK_MAX * ENTRY_SIZE or BLOCK.count >= SCREEN.block_size then
        return false, 'loadout block layout'
    end
    -- The stratagem table's size (0: unknown, no stratagem is looked up): the equip handler's slot search has its
    -- last type but one.
    L.types = L.types or (L.type_last and L.type_last + 2) or 0
    if L.types ~= 0 and (L.types < 2 or L.types > 0x1000) then return false, 'stratagem table size' end
    return true
end

-- The list extras (ready with empty slots, the list kept open after a replacement and its scroll, the
-- clear key, the clear buttons): each is on only when all its code is found and fits; otherwise only that extra is off.
local EXTRA = {ready = false, press = false, emote = false, advance = false, scroll = false, clear = false,
               buttons = false, weapons = false, toggles = false}
local WIDGET = {}  -- the slot widgets: offset from the grid, type offset

local function read_extras()
    local found = code.found
    local function missing(names)
        for _, name in ipairs(names) do
            if not found[name] then return string.format('code "%s" %s', name, code.missing[name] or 'not found') end
        end
    end
    local why = missing(READY_SIGS)
    if not why then
        for _, part in ipairs({'ready_slots', 'ready_toggle'}) do
            if found[part] < L.ready_handler or found[part] > L.ready_handler + 0x800 then
                why = part .. ' outside the ready handler'
            end
        end
    end
    if not why and (L.slot_stride < 0x100 or L.slot_stride > 0x10000 or L.flash >= L.slot_stride) then why = 'slot layout' end
    if not why then
        local ok, fn = pcall(ffi.cast, 'void (*)(uint64_t, uint32_t)', native.base + L.ui_sound)
        if ok then native.sound = fn else why = 'native function sound unavailable' end
    end
    EXTRA.ready, EXTRA.ready_why = not why, why
    -- A Ready press seen while a flash still shows: the handler's own press check on its prompt, with the input
    -- object the UI frame hands the screen.
    why = (not EXTRA.ready and 'needs ready with empty slots') or missing(PRESS_SIGS)
    if not why and (found.ready_entry < L.ready_handler or found.ready_entry > L.ready_handler + 0x40) then
        why = 'ready_entry outside the ready handler'
    end
    if not why and L.press_call ~= found.ready_press then why = 'the ready handler does not call the press check found' end
    if not why and (L.ready_prompt < 0x100 or L.ready_prompt >= L.slot_flags) then why = 'panel layout (prompt)' end
    if not why then
        local ok, fn = pcall(ffi.cast, 'int32_t (*)(uint64_t, uint64_t)', native.base + found.ready_press)
        if ok then native.ready_press = fn else why = 'native function press check unavailable' end
    end
    EXTRA.press, EXTRA.press_why = not why, why
    -- The ready pose: the toggle's event for the panel's unit, sent to every peer through the handler's emote sender.
    why = (not EXTRA.ready and 'needs ready with empty slots') or missing(EMOTE_SIGS)
    if not why and (found.ready_emote < found.ready_toggle or found.ready_emote > found.ready_toggle + 0x100) then
        why = 'ready_emote outside the ready toggle'
    end
    if not why and L.emote ~= found.emote_send then why = 'the ready toggle does not call the emote sender found' end
    if not why and (L.panel_unit <= L.panel_entity or L.panel_unit >= L.ready_timer) then why = 'panel layout (unit)' end
    if not why then
        local ok, fn = pcall(ffi.cast, 'void (*)(uint64_t, uint32_t, uint32_t, float, float)', native.base + found.emote_send)
        if ok then native.emote = fn else why = 'native function emote unavailable' end
    end
    EXTRA.emote, EXTRA.emote_why = not why, why
    why = missing(ADVANCE_SIGS)
    if not why and L.focus_call ~= found.focus then why = 'the equip handler does not focus with the setter found' end
    if not why and L.slot_flags and L.slot_types ~= L.panels + L.slot_flags + SLOT_TYPE then why = 'slot layout' end
    if not why then
        SCREEN.edit = L.edit_slot - L.local_index
        if SCREEN.edit < 0 or SCREEN.edit > 0x1000 then why = 'screen head layout (edited slot)' end
    end
    if not why then
        local ok1, open = pcall(ffi.cast, 'void (*)(uint64_t)', code:address('open_list'))
        local ok2, focus = pcall(ffi.cast, 'void (*)(uint64_t, uint32_t)', code:address('focus'))
        if ok1 and ok2 then native.open, native.focus = open, focus else why = 'native functions unavailable' end
    end
    if not why then SCREEN.head_size = math.max(SCREEN.head_size, SCREEN.edit + 4) end
    EXTRA.advance, EXTRA.advance_why = not why, why
    -- The scroll kept when the list opens again.
    why = (not EXTRA.advance and 'needs the list kept open') or missing(SCROLL_SIGS)
    if not why then
        local ok1, layout = pcall(ffi.cast, 'void (*)(uint64_t)', native.base + L.layout)
        local ok2, list_focus = pcall(ffi.cast, 'uint8_t (*)(uint64_t, uint32_t)', code:address('list_focus'))
        if ok1 and ok2 then native.layout, native.list_focus = layout, list_focus else why = 'native functions unavailable' end
    end
    EXTRA.scroll, EXTRA.scroll_why = not why, why
    -- Clear Stratagems: the slot widgets (grid + widget base + slot * stride, type at +0x128c on this build).
    why = missing(CLEAR_SIGS)
    if not why and not L.list_open then why = 'needs the list-open flag (code "ready_call" or "open_list")' end
    if not why then
        WIDGET.base = L.grid + L.widget_base
        WIDGET.type = L.slot_types - WIDGET.base
        if WIDGET.type < 4 or WIDGET.type >= L.slot_stride then why = 'slot widget layout' end
        if not why and L.slot_flags and L.slot_flags + SLOT_TYPE ~= L.slot_types - L.panels then why = 'slot widget layout' end
    end
    if not why then
        local casts = {set_widget = {'void (*)(uint64_t, uint32_t)', L.set_widget},
                       slots_changed = {'void (*)(uint64_t, int64_t)', L.slots_changed},
                       save = {'void (*)(uint64_t)', L.save}, close = {'void (*)(uint64_t)', L.close_list}}
        for name, c in pairs(casts) do
            local ok, fn = pcall(ffi.cast, c[1], native.base + c[2])
            if ok then native[name] = fn else why = 'native function ' .. name .. ' unavailable' end
        end
    end
    EXTRA.clear, EXTRA.clear_why = not why, why
end

