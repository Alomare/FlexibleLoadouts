-- The Action key pressed on the loadout screen

-- In the stratagem view the hovered slot (with the mouse; its X counts) else the focused one is emptied, and on the
-- booster slot (or the reroll button) the lineup is randomized; in the equipment view the hovered else focused weapon
-- slot's Leave Out toggle flips; with the stratagem list open the hovered else focused stratagem is pinned or
-- unpinned. Nothing while the game would take no click there (ready, another group), or on an empty or armour slot.
-- Without the buttons' code (the slots' hover and focus fields): the former Clear Stratagems, all four at once.
local function press_key(screen, index, list_open)
    if list_open and EXTRA.pins then return pins.key(screen) end
    if not EXTRA.buttons then return clear_loadout(screen, index, list_open) end
    local why, mode = common_gates(screen, list_open)
    local input = global(L.click_input)
    local mouse = input ~= nil and u8_at(input + L.mouse_mode) ~= 0
    local group = u32_at(screen + L.active_group)
    if why and why ~= 'not mouse mode' then
        return note(string.format('Key: nothing (%s; group %s)', why, tostring(group)))
    end
    local hovered, focus, target
    if mode == 0 then
        hovered = buttons.hovered or (dice.hovered and 4) or i32(u32_at(screen + L.grid + L.hovered))
        focus = i32(u32_at(screen + L.grid + L.click_grid_focus))
        target = (mouse and hovered and hovered >= 0 and hovered <= 4) and hovered or focus
    elseif mode == 1 and EXTRA.toggles then
        hovered = toggles.hovered and toggles.hovered + 2 or i32(u32_at(screen + toggles.view + L.view_hovered))
        focus = i32(u32_at(screen + toggles.view + L.view_focus))
        target = (mouse and hovered and hovered >= 0) and hovered or focus
    end
    note(string.format('Key: mode %s, %s, group %s, hovered %s, focused %s', tostring(mode),
                       mouse and 'mouse' or 'controller', tostring(group), tostring(hovered), tostring(focus)))
    if mode == 0 and target and target >= 0 and target <= 3 then
        local flags = read(screen + WIDGET.base + target * L.slot_stride + L.widget_flags, 8)
        if flags and u32(flags, 4) ~= 0 and bit.band(flags:byte(1), DISABLED_BIT) == 0 then
            return clear_slot(screen, index, target, 'key')
        end
        return note('Key: that stratagem slot is empty')
    elseif mode == 0 and target == 4 then
        if EXTRA.dice then return dice.start(screen, index, 'key') end
        return note('Key: the booster slot (Randomize Lineup not available)')
    elseif mode == 1 and target and target >= 3 and target <= 5 then
        return flip_toggle(target - 2)
    end
    note('Key: nothing to do there')
end

