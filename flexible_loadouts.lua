-- Logging and status

local function open_log(name)
    if loader and type(loader.open_log) == 'function' then
        local ok, f = pcall(loader.open_log, name)
        if ok then return f end
    end
end

local log_file = open_log('FlexibleLoadouts.log')
local log_lines = 0

local function note(msg)
    if not log_file or log_lines >= 1000 then return end
    log_lines = log_lines + 1
    pcall(function()
        log_file:write(string.format('[f%d] %s\n', M.frames, msg))
        log_file:flush()
    end)
end

local function write_status(verdict, details)
    local f = open_log('FlexibleLoadouts_STATUS.log')
    if not f then return end
    pcall(function()
        f:write(verdict .. '\n' .. TITLE .. '\n')
        for _, line in ipairs(details or {}) do f:write(line .. '\n') end
        f:close()
    end)
end

