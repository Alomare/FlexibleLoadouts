-- Randomize Lineup

-- The randomizer's code: the X's (widgets, gates, the click) and Clear Stratagems' (slot widgets, the save), the
-- stratagem data fields, the owned check, the booster widget, the game's slot setter. Sets EXTRA.dice.
function dice.read()
    local why = (not EXTRA.buttons and ('needs the clear buttons: ' .. tostring(EXTRA.buttons_why)))
                or H.missing_fields(H.DICE_FIELDS) or (not code.found.set_slot and 'code "set_slot" not found') or nil
    if not why and L.types ~= L.owned_end then
        why = string.format('the owned loop ends at %s, the stratagem table at %s', tostring(L.owned_end), tostring(L.types))
    end
    if not why and (L.info_hud >= 0x400 or L.info_flags >= 0x400 or L.ban_stride < 0x20 or L.ban_stride > 0x400) then
        why = 'stratagem data layout'
    end
    if not why then
        dice.fn = {}
        local casts = {owned = {'uint8_t (*)(uint64_t, uint32_t)', L.owned_call},
                       set_slot = {'void (*)(uint64_t, uint32_t, uint32_t)', code.found.set_slot}}
        for name, c in pairs(casts) do
            local ok, f = pcall(ffi.cast, c[1], native.base + c[2])
            if ok then dice.fn[name] = f else why = why or ('native function ' .. name .. ' unavailable') end
        end
        dice.sounds = {[0] = L.pick_red or L.click_sound, [2] = L.pick_blue or L.click_sound,
                       [3] = L.pick_green or L.click_sound}
    end
    EXTRA.dice, EXTRA.dice_why = not why, why
end

function H.dice_fail(why)
    dice.failed = why
    H.dice_note('Randomize Lineup stopped for the session: ' .. why)
end

-- A small random generator of the mod's own (xorshift32), so other mods' math.random stays as they left it.
H.seed = bit.tobit((os.time() * 69069 + math.floor(os.clock() * 1000)) % 4294967296)
if H.seed == 0 then H.seed = 1 end
function H.random(n)  -- 1..n
    H.seed = bit.bxor(H.seed, bit.lshift(H.seed, 13))
    H.seed = bit.bxor(H.seed, bit.rshift(H.seed, 17))
    H.seed = bit.bxor(H.seed, bit.lshift(H.seed, 5))
    return H.seed % n + 1
end

function H.class_of(hud, flags)
    local colour = H.HUD[hud]
    if colour ~= 'blue' then return colour end
    if bit.band(flags, H.FLAG.vehicle) ~= 0 then
        return bit.band(flags, L.kind_tank) == 0 and 'vehicle' or nil  -- Exosuits and FRVs, not tanks
    elseif bit.band(flags, H.FLAG.expendable) ~= 0 then return 'expendable'
    elseif bit.band(flags, H.FLAG.weapon) ~= 0 then
        return bit.band(flags, H.FLAG.backpack) ~= 0 and 'fed' or 'weapon'
    elseif bit.band(flags, H.FLAG.backpack) ~= 0 then return 'backpack' end
    return nil
end

-- Item id -> banned for now (the offer's record byte the game's press refuses on), from the stratagem range.
function H.bans()
    local map = {}
    local offers = global(L.offers)
    local first = offers and u32_at(offers + L.first)
    local last = offers and u32_at(offers + L.last)
    if not first or not last or last <= first or last - first > 512 then return map end
    local indices = read(offers + L.indices + first * 4, (last - first) * 4)
    for k = 0, last - first - 1 do
        local index = u32(indices, k * 4)
        local entry = index and read(offers + L.entries + index * OFFER_STRIDE, OFFER_STRIDE)
        local record = entry and u32(entry, 0)
        local byte = record and record < 0x10000 and u8_at(offers + L.ban_base + record * L.ban_stride)
        if byte and byte ~= 0 then map[u32(entry, OFFER_ITEM)] = true end
    end
    return map
end

function H.choose(n, k)
    if n < k then return 0 end
    local r = 1
    for i = 0, k - 1 do r = r * (n - i) / (i + 1) end
    return r
end

function H.pool(name)
    local out = {}
    for _, class in ipairs(H.POOLS[name]) do
        for _, s in ipairs(dice.classes[class]) do out[#out + 1] = s end
    end
    return out
end

-- The ways a lineup can be filled (each slot's pool used k times: k different stratagems).
function H.ways(lineup)
    local uses = {}
    for _, p in ipairs(lineup) do uses[p] = (uses[p] or 0) + 1 end
    local w = 1
    for p, k in pairs(uses) do w = w * H.choose(#H.pool(p), k) end
    return w
end

-- The owned stratagems by class (the game's owned check, as for the list), without banned ones; then each lineup's
-- ways. Logged when it changes.
function H.count_pool()
    local offers = global(L.offers)
    if not offers then return end
    local banned = H.bans()
    local classes, names = {}, {}
    for _, c in ipairs(H.CLASSES) do classes[c], names[c] = {}, {} end
    for t = 1, L.types - 1 do
        local info = info_of(t)
        if info and dice.fn.owned(offers, t) ~= 0 then
            local item, hud, flags = u32_at(info + INFO_ID), u32_at(info + L.info_hud), u32_at(info + L.info_flags)
            local class = item and hud and flags and H.class_of(hud, flags)
            if class and not banned[item] then
                local list = classes[class]
                list[#list + 1] = {type = t, item = item, hud = hud, vehicle = class == 'vehicle'}
                local name = pointer_at(info + 0x10)
                local text = name and read(name, 48)
                names[class][#names[class] + 1] = text and text:match('^[^%z]*') or tostring(t)
            end
        end
    end
    dice.classes = classes
    local w, counts = {}, {}
    for i, lineup in ipairs(H.LINEUPS) do w[i] = H.ways(lineup) end
    for _, c in ipairs(H.CLASSES) do counts[#counts + 1] = c .. ' ' .. #classes[c] end
    dice.ways = w
    local text = string.format('Randomize Lineup: owned %s; lineups 1-3: %d, %d, %d ways', table.concat(counts, ', '),
                               w[1], w[2], w[3])
    if text ~= dice.pooled then
        dice.pooled = text
        H.dice_note(text)
        if not dice.named then
            dice.named = true
            for _, c in ipairs(H.CLASSES) do
                H.dice_note(string.format('Randomize Lineup: %s: %s', c, table.concat(names[c], ', ')))
            end
        end
    end
end

function H.randomizable()
    local w = dice.ways
    return w ~= nil and math.max(w[1], w[2], w[3]) >= 2
end

function H.slot_widget(screen, k) return screen + WIDGET.base + k * L.slot_stride end

-- A lineup drawn: one of the lineups that can be filled, its slots filled at random (different stratagems), tried
-- again a few times when it equals the loadout already there.
function H.draw_lineup(screen)
    local options = {}
    for i, w in ipairs(dice.ways) do if w >= 1 then options[#options + 1] = i end end
    if #options == 0 then return nil end
    local current = {}
    for k = 0, 3 do current[k + 1] = u32_at(H.slot_widget(screen, k) + WIDGET.type) or 0 end
    local picks, which
    for _ = 1, 12 do
        which = options[H.random(#options)]
        picks = {}
        local used, same = {}, true
        for k, p in ipairs(H.LINEUPS[which]) do
            local free = {}
            for _, s in ipairs(H.pool(p)) do if not used[s.type] then free[#free + 1] = s end end
            local s = free[H.random(#free)]
            used[s.type], picks[k] = true, s
            if s.type ~= current[k] then same = false end
        end
        if not same then break end
    end
    return picks, which
end

-- A roll: its slots one at a time (the next after the delay). Starts with the first slot at once.
function dice.start(screen, index, why)
    if dice.roll then return H.dice_note('Randomize Lineup: already rolling') end
    if dice.failed then return end
    H.count_pool()
    if not H.randomizable() then return H.dice_note('Randomize Lineup: not enough stratagems (' .. why .. ')') end
    local picks, which = H.draw_lineup(screen)
    if not picks then return end
    local types = {}
    for k, s in ipairs(picks) do types[k] = string.format('%d', s.type) end
    H.dice_note(string.format('Randomize Lineup: lineup %d (%s; %s)', which, table.concat(types, ', '), why))
    dice.roll = {screen = screen, index = index, picks = picks, k = 0, at = M.time}
end

-- Each frame: the roll's next slot when its time came. A slot disabled by the mission is left as it is. Stopped when
-- the screen goes, the list opens, the equipment view shows or the player readies.
function dice.service_roll(screen, list_open)
    local R = dice.roll
    if not R then return end
    local stop = (screen ~= R.screen and 'the screen left') or (list_open and 'the list opened')
                 or (u32_at(screen + L.grid_mode) ~= 0 and 'the equipment view')
                 or (EXTRA.ready and u32_at(screen + L.panels + L.ready_timer) ~= L.timer_idle and 'ready') or nil
    if stop then
        dice.roll = nil
        return H.dice_note(string.format('Randomize Lineup: stopped after %d slot(s) (%s)', R.k, stop))
    end
    while R.k < 4 and M.time >= R.at do
        local k = R.k
        R.k = k + 1
        local widget = H.slot_widget(screen, k)
        local flags = read(widget + L.widget_flags, 2)
        if flags and bit.band(flags:byte(1), DISABLED_BIT) == 0 then
            local pick = R.picks[k + 1]
            -- A later slot holding this stratagem (or a vehicle, when this is one) is emptied now and filled at its
            -- turn: no repeat or second vehicle even for a moment, nor if the roll stops.
            for j = k + 1, 3 do
                local other = H.slot_widget(screen, j)
                local t = u32_at(other + WIDGET.type)
                local info = t and t ~= 0 and pick.vehicle and info_of(t)
                local vehicle = info and bit.band(u32_at(info + L.info_flags) or 0, H.FLAG.vehicle) ~= 0
                if t and t ~= 0 and (t == pick.type or vehicle) then native.set_widget(other, 0) end
            end
            dice.fn.set_slot(screen + L.panels, k, pick.item)
            native.slots_changed(screen + L.panels, -1)
            native.save(screen + L.block_base + R.index * L.block_stride)
            local sound = dice.sounds[pick.hud]
            if sound then buttons.fn.sound(0, sound) end
            R.at = M.time + H.DICE.delay
        end
    end
    if R.k >= 4 then
        dice.roll = nil
        H.dice_note('Randomize Lineup: done')
    end
end

-- Each frame on the loadout screen: the button under the booster widget (made and fully checked every few frames),
-- shown while a lineup can be filled two ways, hovered and clicked when the game would take a click on the slots.
function dice.service(screen, index, list_open)
    local D = dice
    if D.failed then return end
    if D.screen ~= screen then D.screen, D.button = screen, nil end
    local full = M.frames % CHECK_EVERY == 0 or D.checked ~= D.visit
    if D.checked ~= D.visit or M.frames % H.POOL_EVERY == 0 then H.count_pool() end
    D.checked = D.visit
    local booster = screen + L.grid + L.booster_at
    local b = D.button
    if b and full then
        local lost = H.lost_mark(b, D.visit)
        if lost then
            H.dice_note('Randomize Lineup: the button lost (' .. lost .. ')')
            b, D.button = nil, nil
        else
            b.visit = D.visit
        end
    end
    local wanted = H.randomizable()
    if not b and full and wanted and u32_at(booster) ~= 0 then
        if D.mark == nil then D.mark = H.loaded(H.DICE.name, 'Randomize Lineup') end
        b = H.build_mark(booster, 'Randomize Lineup', H.dice_fail, {anchor = {0, 0}, x = H.DICE.x, y = H.DICE.y,
                                                              size = H.DICE.size, icon = H.DICE.icon, layer = H.DICE.layer},
                       H.DICE.material, D.mark)
        if not b then return end
        b.visit = D.visit
        D.button = b
        H.dice_note(string.format('Randomize Lineup: button made under the booster (%s); booster at %s; slot 4 at %s',
                                D.mark and 'the refresh arrows' or 'a square', rect_text(booster),
                                rect_text(H.slot_widget(screen, 3))))
    end
    if not b then return end
    local open = gates(screen, list_open)
    local ui = buf_pointer(buffers.global, 0)
    local shown = wanted and u32_at(b.pieces.plate) ~= 0
    local over = shown and open and not D.roll and ui ~= nil and buttons.fn.hit(ui + L.cursor_widget, b.pieces.plate, 0) ~= 0
    H.show_mark(b, shown, over and BUTTON.plate_hover or BUTTON.plate, over and H.DICE.hover or H.DICE.colour)
    if shown and b.logged ~= D.visit then
        b.logged = D.visit
        H.dice_note('Randomize Lineup: shown at ' .. rect_text(b.pieces.plate))
    end
    if buttons.highlight then service_highlight(D.under, H.slot_widget(screen, 3), over, ui) end
    if over ~= (D.hovered == true) then
        H.dice_note(over and 'Randomize Lineup: hovered' or 'Randomize Lineup: left')
        D.hovered = over or nil
    end
    -- A click: hovered now and blocked since the frame before (the slots' hovered index none), so the game ignored it.
    if over and D.blocked and confirm_pressed() then dice.start(screen, index, 'clicked') end
    if over then write(screen + L.grid + L.hovered, u32_bytes(0xffffffff)) end
    D.blocked = over or nil
end
end

