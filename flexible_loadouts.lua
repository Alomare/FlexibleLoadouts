-- The toggles' code: the buttons' (widgets, gates, fades), the weapon code (what the toggles act on), every
-- signature found and agreeing, the equipment slots laid out as the view's own slots. Sets EXTRA.toggles.
function read_toggles()
    local found = code.found
    local why = (not EXTRA.buttons and ('needs the clear buttons: ' .. tostring(EXTRA.buttons_why)))
                or (not EXTRA.weapons and ('needs the weapon code: ' .. tostring(EXTRA.weapons_why))) or nil
    for _, name in ipairs(CODE.sigs) do
        if not why and not found[name] then why = string.format('code "%s" %s', name, code.missing[name] or 'not found') end
    end
    for _, same in ipairs(CODE.same) do
        if not why and L[same[1]] ~= L[same[2]] then why = string.format('"%s" differs from "%s"', same[1], same[2]) end
    end
    if not why and L.view_slot_redraw ~= found.view_slot_redraw then why = 'the view hover calls another slot redraw' end
    for _, call in ipairs(CODE.title_calls) do
        if not why and L[call[1]] ~= found[call[2]] then
            why = string.format('the title build calls %s at %s, not the one found', call[2], tostring(L[call[1]]))
        end
    end
    if not why and L.text_set_label ~= L.call_set_label then why = '"text_set_label" differs from "call_set_label"' end
    if not why and (L.label_type ~= 7 or L.label_last + 4 > TOGGLE.label_size) then why = 'label layout' end
    if not why and (found.view_click < L.view_input or found.view_click > L.view_input + 0x300) then
        why = 'view_click outside the view input'
    end
    if not why and (L.vr_opacity_set ~= found.widget_opacity_set or L.vr_color_set ~= found.widget_color_set) then
        why = 'the slot redraw calls other widget setters'
    end
    local first = not why and L.vh_flags_at - L.vr_flags
    for k, field in pairs(CODE.slot_fields) do
        if not why and L[field] ~= first + k * L.view_slot_stride then why = 'equipment slot layout (' .. field .. ')' end
    end
    local section = not why and L.gates_grid_mode - L.sec_mode
    if not why and (section <= 0 or L.gates_view <= section or L.gates_view - section > 0x10000
                    or L.view_hovered < first + 6 * L.view_slot_stride or L.view_hovered > 0x10000  -- after the slots
                    or L.sec_transition ~= L.sec_mode + 4) then
        why = 'equipment view layout'
    end
    if not why then
        toggles.view = L.gates_view
        toggles.transition = section + L.sec_transition
        toggles.slots_at = {L.gates_view + L.slot_primary, L.gates_view + L.slot_secondary, L.gates_view + L.slot_throwable}
        toggles.frame_colour = L.vr_frame + 0x48  -- the frame's colour (class 0x17909F0, as for the stratagem slots)
        local ok, f = pcall(ffi.cast, 'void (*)(uint64_t)', native.base + L.view_slot_redraw)
        if ok then toggles.redraw = f else why = 'native function view slot redraw unavailable' end
        local rvas = {label_init = found.label_init, set_label = L.call_set_label,
                      set_string_arg = L.call_set_string_arg, font_set = found.font_set,
                      font_size_set = L.call_font_size_set, measure = found.widget_measure,
                      children_refresh = L.call_children_refresh}
        toggles.fn = {}
        for short, rva in pairs(rvas) do
            local good, fn = pcall(ffi.cast, CODE.fn[short], native.base + rva)
            if good then toggles.fn[short] = fn else why = why or ('native function ' .. short .. ' unavailable') end
        end
    end
    EXTRA.toggles, EXTRA.toggles_why = not why, why
end

