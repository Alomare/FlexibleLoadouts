-- The buttons' code: every signature found, its fields agreeing with the core's, the functions with the game's own
-- calls, the layout fitting the slot widgets Clear Stratagems uses. Sets EXTRA.buttons.
local function read_buttons()
    local found = code.found
    local why = nil
    for _, name in ipairs(BUTTON_SIGS) do
        if not why and not found[name] then why = string.format('code "%s" %s', name, code.missing[name] or 'not found') end
    end
    if not why and not EXTRA.clear then why = 'needs the Clear Stratagems code: ' .. tostring(EXTRA.clear_why) end
    if not why and not L.timer_idle then why = 'needs the ready timer (code "ready_toggle")' end
    for _, same in ipairs(SAME) do
        if not why and L[same[2]] ~= nil and L[same[1]] ~= L[same[2]] then
            why = string.format('"%s" differs from "%s"', same[1], same[2])
        end
    end
    if not why and L.widget_flags + 4 ~= WIDGET.type then why = 'slot widget layout (flags, type)' end
    if not why and L.context_stack_next ~= L.context_stack + 1 then why = 'the context stack offsets disagree' end
    if not why and (found.grid_gates < L.screen_input or found.grid_gates > L.screen_input + 0x400) then
        why = 'grid_gates outside the panel input'
    end
    if not why and (found.grid_click < L.grid_input or found.grid_click > L.grid_input + 0x400) then
        why = 'grid_click outside the grid input'
    end
    if not why and L.panel_local and L.panel_local_at ~= L.panels + L.panel_local then why = 'panel layout (local)' end
    if not why and L.timer_at ~= L.panels + L.ready_timer then why = 'panel layout (ready timer)' end
    local groups = {}
    for _, names in ipairs(GATE_GROUPS) do
        local lo, hi = math.huge, -1
        for _, n in ipairs(names) do
            if L[n] then lo, hi = math.min(lo, L[n]), math.max(hi, L[n] + 4) end
        end
        if not why and (hi < 0 or hi - lo > 0x100) then why = 'gate layout (' .. names[1] .. ')' end
        groups[#groups + 1] = {names = names, lo = lo, size = hi - lo}
    end
    local fn = {}
    if not why then
        local rvas = {hit = L.hit_test, action_index = L.action_index, sound = L.click_ui_sound,
                      context_push = found.ui_context, context_pop = found.ui_context + POP_AFTER_PUSH}
        for short, src in pairs(FN_SOURCES) do
            rvas[short] = found[src[1]]
            if not why and src[2] and L[src[2]] ~= found[src[1]] then
                why = string.format('%s at %x, but the game calls %s', src[1], found[src[1]], tostring(L[src[2]]))
            end
        end
        for short, rva in pairs(rvas) do
            local ok, f = pcall(ffi.cast, FN_TYPES[short], native.base + rva)
            if ok then fn[short] = f else why = why or ('native function ' .. short .. ' unavailable') end
        end
    end
    -- The extras, each off alone: the slot unhovered under its X (the game's set-hover and redraw named by slot_hover,
    -- the dirty mark), and the X's fades (the game's fade helper, its tail calling the opacity setter found).
    local function extra(sigs, check, names)
        if why then return false, 'the buttons are off' end
        for _, name in ipairs(sigs) do
            if not found[name] then return false, string.format('code "%s" %s', name, code.missing[name] or 'not found') end
        end
        local bad = check()
        if bad then return false, bad end
        for short, rva in pairs(names) do
            local ok, f = pcall(ffi.cast, FN_TYPES[short], native.base + rva)
            if not ok then return false, 'native function ' .. short .. ' unavailable' end
            fn[short] = f
        end
        return true
    end
    buttons.highlight, buttons.highlight_why = extra(HIGHLIGHT_SIGS, function()
        if L.dirty_parent ~= L.widget_parent then return '"dirty_parent" differs from "widget_parent"' end
    end, {slot_set_hover = L.slot_set_hover, slot_redraw = L.slot_redraw, mark_dirty = found.widget_mark_dirty})
    buttons.fade, buttons.fade_why = extra(FADE_SIGS, function()
        if found.widget_fade_tail < found.widget_fade or found.widget_fade_tail > found.widget_fade + 0x200 then
            return 'the fade tail outside the fade'
        end
        if L.fade_opacity_set ~= found.widget_opacity_set then return 'the fade calls another opacity setter' end
    end, {fade = found.widget_fade})
    if not why then
        buttons.fn, buttons.groups = fn, groups
        buttons.pair = ffi.new('union { float f[2]; uint64_t u; }')
        buttons.rgb = ffi.new('float[3]')
    end
    EXTRA.buttons, EXTRA.buttons_why = not why, why
end

local function pair(x, y)
    buttons.pair.f[0], buttons.pair.f[1] = x, y
    return buttons.pair.u
end

local function rgb(c)
    buttons.rgb[0], buttons.rgb[1], buttons.rgb[2] = c[1], c[2], c[3]
    return buttons.rgb
end

local function allocate(size)  -- zeroed, 16-byte aligned, kept for the session
    local block = ffi.new('uint8_t[?]', size + 16)
    buttons.keep[#buttons.keep + 1] = block
    local at = tonumber(ffi.cast('uint64_t', block))
    return at + (16 - at % 16) % 16
end

-- Whether the game's own cross can be used: its resource loaded (asked once).
local function mark_available()
    if buttons.mark == nil then
        local ok, res = pcall(function() return stingray.Application.can_get('material', CHECK_NO_NAME) end)
        buttons.mark = ok and res == true
        button_note('Clear buttons: ' .. CHECK_NO_NAME .. (buttons.mark and ' is loaded' or ' is not loaded')
                    .. (ok and '' or (' (' .. tostring(res) .. ')')))
    end
    return buttons.mark
end

local function fail(why)
    buttons.failed = why
    button_note('Clear buttons stopped for the session: ' .. why)
end

-- Runs make(context) inside the slot's GUI context (pushed, then popped and the stack checked), so the widgets it
-- makes belong to the slot's context. Returns true, or nil after fail_with(why). what names the caller in the log.
local function in_slot_context(slot, what, fail_with, make)
    local fn = buttons.fn
    local base = global(L.gui_contexts)
    local context = pointer_at(slot + L.widget_context)
    if not (base and context) then return fail_with('no GUI context') end
    local index = (context - base) / L.context_stride
    if index ~= math.floor(index) or index < 0 or index >= CONTEXT_SLOTS then
        return fail_with(string.format('the slot context %x is not a slot of %x', context, base))
    end
    if u8_at(context) ~= 1 then return fail_with('the slot context is not live') end
    local top = i32(u32_at(base + L.context_top))
    if not top or top < -1 or top > STACK_SLOTS - 2 then return fail_with('context stack top ' .. tostring(top)) end
    local before = top >= 0 and u8_at(base + L.context_stack + top) or nil
    button_note(string.format('%s: building (slot %x, GUI context slot %d, stack top %d)', what, slot, index, top))
    fn.context_push(base, index)  -- (a crash log names the step above)
    if i32(u32_at(base + L.context_top)) ~= top + 1 or u8_at(base + L.context_stack + top + 1) ~= index then
        return fail_with('the context push did not take')
    end
    local ok, err = pcall(make, context)
    if i32(u32_at(base + L.context_top)) == top + 1 then fn.context_pop() end
    if i32(u32_at(base + L.context_top)) ~= top or (before and u8_at(base + L.context_stack + top) ~= before) then
        return fail_with('the context stack was not restored')
    end
    if not ok then return fail_with('making a button: ' .. tostring(err)) end
    return true
end

-- A picture piece made in the current context: {material, w, h, anchor, pivot, position, layer, rotation}, hidden.
local function make_picture(at, context, p)
    local fn = buttons.fn
    fn.picture_init(at)
    if pointer_at(at + L.widget_context) ~= context then error('a piece is not in the slot context') end
    fn.material_set(at, p.material, 0)
    fn.size_set(at, pair(p.w, p.h))
    fn.anchor_set(at, pair(p.anchor and p.anchor[1] or 1, p.anchor and p.anchor[2] or 1))  -- the top-right corner
    fn.pivot_set(at, pair(p.pivot[1], p.pivot[2]))
    fn.position_set(at, pair(p.x, p.y))
    if p.rotation then fn.rotation_set(at, p.rotation) end
    fn.layer_set(at, p.layer)
    fn.opacity_set(at, 0)
end

-- Attaches the pieces (in order) under the slot, each checked.
local function attach_pieces(slot, pieces, order)
    if u32_at(slot) == 0 then error('the slot died') end
    for _, name in ipairs(order) do
        buttons.fn.attach(slot, pieces[name])
        if pointer_at(pieces[name] + L.widget_parent) ~= slot then error('a piece is not attached to the slot') end
    end
end

-- Makes slot k's button (its pieces: the plate, then the cross, or two bars when it is not loaded) inside the slot's
-- GUI context, attached under the slot. Returns the button, or nil (after fail() when something is wrong).
local function build_button(slot, k)
    local b = {slot = slot, k = k, visit = buttons.visit, pieces = {}, cache = {}, visible = false, unhovered = false}
    local c, centre = BUTTON.centre, {0.5, 0.5}
    local plan = {{name = 'plate', material = GUI_FILL, w = BUTTON.size, h = BUTTON.size}}
    if mark_available() then
        plan[2] = {name = 'mark', material = CHECK_NO, w = BUTTON.size, h = BUTTON.size}
    else
        plan[2] = {name = 'bar_a', material = GUI_FILL, w = BUTTON.bar[1], h = BUTTON.bar[2], rotation = 45}
        plan[3] = {name = 'bar_b', material = GUI_FILL, w = BUTTON.bar[1], h = BUTTON.bar[2], rotation = -45}
    end
    local order = {}
    for i, p in ipairs(plan) do
        p.pivot, p.x, p.y, p.layer = centre, c, c, BUTTON.layer + (i == 1 and 0 or 1)
        b.pieces[p.name], order[i] = allocate(WIDGET_SIZE), p.name
    end
    local ok = in_slot_context(slot, 'Clear buttons', fail, function(context)
        for _, p in ipairs(plan) do
            make_picture(b.pieces[p.name], context, p)
            b.cache[b.pieces[p.name]] = {}
        end
        attach_pieces(slot, b.pieces, order)
    end)
    if not ok then return nil end
    buttons.made = (buttons.made or 0) + 1
    button_note(string.format('Clear buttons: slot %d button made (%s; %d made this session)', k + 1,
                              b.pieces.mark and 'with the cross' or 'without the cross', buttons.made))
    return b
end

-- Whether piece at is in the slot's child list (the list is short: the slot's own pieces plus ours).
local function is_child(slot, at)
    local node = pointer_at(slot + L.first_child)
    for _ = 1, 64 do
        if not node then return false end
        if node == at then return true end
        node = pointer_at(node + L.next_sibling)
    end
    return false
end

-- A full check of a button (every few frames, and on each visit's first frame): every piece alive (header non-zero:
-- the game zeroes a widget it tears down), under the slot and in its child list. Else the button is dropped: an
-- orphan of this visit (the game re-made the slot) is destroyed, an older one only forgotten (its context may be gone).
local function check_button(b)
    local lost = nil
    for name, at in pairs(b.pieces) do
        if u32_at(at) == 0 then lost = lost or (name .. ' torn down')
        elseif pointer_at(at + L.widget_parent) ~= b.slot then lost = lost or (name .. ' has another parent')
        elseif not is_child(b.slot, at) then lost = lost or (name .. " not in the slot's children") end
    end
    if not lost then return true end
    local destroy = b.visit == buttons.visit
    button_note(string.format('Clear buttons: slot %d button lost (%s); %s', b.k + 1, lost,
                              destroy and 'destroying its pieces' or 'forgotten (an earlier visit)'))
    if destroy then
        for _, at in pairs(b.pieces) do
            if u32_at(at) ~= 0 then buttons.fn.destroy(at) end
        end
    end
    return false
end

-- The colour setter, only on a change and never on a piece the game tore down (the next full check drops it).
local function set_colour(b, at, colour)
    local c = b.cache[at]
    if c.colour ~= colour and u32_at(at) ~= 0 then c.colour = colour; buttons.fn.color_set(at, rgb(colour)) end
end

local PIECES = {'plate', 'mark', 'bar_a', 'bar_b'}

-- Shows a button or hides it, hovered or not. A change of shown starts the game's own fade on each piece (in 0.2 s,
-- out 0.1 s; the game's tween pool runs it), or sets the opacity at once without the fade code, or when the slot
-- under it emptied (gone): the opacity setter also ends a running fade.
local function show_button(b, shown, hovered, gone)
    local p = b.pieces
    if shown ~= b.visible then
        b.visible = shown
        for _, name in ipairs(PIECES) do
            local at = p[name]
            if at and u32_at(at) ~= 0 then
                local alpha = name == 'plate' and BUTTON.plate_alpha or 1
                if buttons.fade and not (gone and not shown) then
                    buttons.fn.fade(at, shown and 0 or 1, shown and BUTTON.fade_in or BUTTON.fade_out, alpha, 0)
                else
                    buttons.fn.opacity_set(at, shown and alpha or 0)
                end
            end
        end
    end
    local red = hovered and BUTTON.red_hover or BUTTON.red
    set_colour(b, p.plate, hovered and BUTTON.plate_hover or BUTTON.plate)
    for _, name in ipairs({'mark', 'bar_a', 'bar_b'}) do
        if p[name] then set_colour(b, p[name], red) end
    end
end

-- The slot under a hovered X looks unhovered: on the X the game's own set-hover(slot, off) (its unhovered look, no
-- sound), and each frame the dirty mark, so the game skips the slot's hover test next frame (it would hover the slot
-- again, with its sound: the X is inside the slot). Off the X onto the slot body, the mod hovers it again without the
-- sound, as the game's set-hover would. Whatever stops, the slot is left in the game's own "not hovered" state.
local function service_highlight(b, slot, on_x, ui)
    local fn = buttons.fn
    if on_x then
        local flags = read(slot + L.widget_flags, 2)
        if flags and bit.band(flags:byte(1), 1) ~= 0 then fn.slot_set_hover(slot, 0) end
        fn.mark_dirty(slot)
        if not b.unhovered then button_note(string.format('Clear buttons: slot %d unhovered under its X', b.k + 1)) end
        b.unhovered = true
    elseif b.unhovered then
        b.unhovered = false
        local flags = read(slot + L.widget_flags, 2)
        local again = flags and u32_at(slot) ~= 0 and bit.band(flags:byte(1), 5) == 0 and ui ~= nil
                      and fn.hit(ui + L.cursor_widget, slot, 0) ~= 0
        if again then
            write(slot + L.widget_flags, string.char(bit.bor(flags:byte(1), 1), flags:byte(2)))
            fn.slot_redraw(slot)
        end
        button_note(string.format('Clear buttons: slot %d %s', b.k + 1, again and 'hovered again (the X left)'
                                  or 'left unhovered (the cursor left it)'))
    end
end

-- The game's own conditions for taking a click on a local slot (screen_gates, grid_gates), in mouse mode, read once
-- a frame for the X's and the Leave Out toggles: nil (all pass) or the first that fails, and the panel's mode (0 the
-- stratagem grid, 1 the equipment view; nil when unread).
local frame_gates = {frame = nil, why = nil, mode = nil}

local function common_gates(screen, list_open)
    local G = frame_gates
    if G.frame == M.frames then return G.why, G.mode end
    local why = list_open and 'the list is open' or nil
    local v = {}
    if not why then
        for _, g in ipairs(buttons.groups) do
            local blob = read(screen + g.lo, g.size)
            if not blob then why = 'unreadable'; break end
            for _, n in ipairs(g.names) do v[n] = blob:sub(L[n] - g.lo + 1, L[n] - g.lo + 4) end
        end
    end
    local mode = not why and u32(v.gates_grid_mode) or nil
    if why then
    elseif u32(v.screen_state) ~= SCREEN_ACTIVE then why = 'screen state'
    elseif v.launching:byte(1) ~= 0 then why = 'launching'
    elseif (f32(v.input_delay, 0) or 1) > 0 then why = 'input delay'
    elseif v.busy_a:byte(1) ~= 0 or v.busy_b:byte(1) ~= 0 or v.busy_c:byte(1) ~= 0 then why = 'busy'
    elseif not STATE_A[u32(v.state_a)] or not STATE_B[u32(v.state_b)] then why = 'state'
    elseif u32(v.active_group) ~= 0 then why = 'another group'
    elseif v.panel_busy:byte(1) ~= 0 or v.panel_local_at:byte(1) == 0 then why = 'panel'
    elseif u32(v.timer_at) ~= L.timer_idle then why = 'ready'
    else
        local input = global(L.click_input)
        if not input or u8_at(input + L.mouse_mode) == 0 then why = 'not mouse mode' end
    end
    G.frame, G.why, G.mode = M.frames, why, mode
    return why, mode
end

-- The X's: the common gates in grid mode 0 with the grid active (grid_click). Returns whether a click is taken (the
-- first gate that fails is logged on change), and the slot to mark when only mouse mode fails: with a controller the
-- focused slot's X shows (no click), for the Action key.
local function gates(screen, list_open)
    local why, mode = common_gates(screen, list_open)
    if why and why ~= 'not mouse mode' then
    elseif mode ~= 0 then why = 'grid mode'
    elseif u8_at(screen + L.grid + L.grid_active) == 0 then why = 'grid inactive' end
    local pad_slot = nil
    if why == 'not mouse mode' then
        local focus = i32(u32_at(screen + L.grid + L.click_grid_focus))
        if focus and focus >= 0 and focus <= 3 then pad_slot = focus end
    end
    local text = why and ('hidden (' .. why .. ')' .. (pad_slot and (', slot ' .. (pad_slot + 1) .. ' marked') or '')) or 'shown'
    if text ~= buttons.gates then
        buttons.gates = text
        button_note('Clear buttons: ' .. text)
    end
    return why == nil, pad_slot
end

-- The confirm press of this frame (the game's press bytes, read after its input ran).
local function confirm_pressed()
    local input = global(L.click_input)
    if not input then return false end
    local index = buttons.fn.action_index(CONFIRM_ACTION)
    return index < 0x400 and u8_at(input + L.press_base + index * PRESS_STRIDE) ~= 0
end

local function rect_text(at)
    local w = read(at, 0xa0)
    if not w then return '?' end
    return string.format('x %.1f y %.1f, %.1f x %.1f (size %.0f x %.0f)', f32(w, 0x94) or 0, f32(w, 0x9c) or 0,
                         (f32(w, 0x64) or 0) * (f32(w, 0x24) or 0), (f32(w, 0x8c) or 0) * (f32(w, 0x28) or 0),
                         f32(w, 0x24) or 0, f32(w, 0x28) or 0)
end

-- Empties stratagem slot k the Clear Stratagems way, with the remove sound.
local function clear_slot(screen, index, k, why)
    native.set_widget(screen + WIDGET.base + k * L.slot_stride, 0)
    native.slots_changed(screen + L.panels, -1)
    native.save(screen + L.block_base + index * L.block_stride)
    buttons.fn.sound(0, REMOVE_SOUND)
    button_note(string.format('Clear buttons: slot %d emptied (%s)', k + 1, why))
end

-- Each frame on the loadout screen (local index set): the gates, then per slot its button (made and fully checked
-- every few frames), shown or hidden, hovered; a click; the block for the next frame.
local function service_buttons(screen, index, list_open)
    local B = buttons
    if B.failed then return end
    if B.screen ~= screen then
        if B.screen then button_note(string.format('Clear buttons: another screen object (%x, was %x)', screen, B.screen)) end
        B.screen, B.slots = screen, {}
    end
    if B.cleared and B.cleared.frame == M.frames - 1 then
        button_note(list_open and 'Clear buttons: THE LIST OPENED after an X click' or 'Clear buttons: no list after the click')
        B.cleared = nil
    end
    local full = M.frames % CHECK_EVERY == 0 or B.checked ~= B.visit
    B.checked = B.visit
    local open, pad_slot = gates(screen, list_open)
    local ui = buf_pointer(buffers.global, 0)
    local hovered = nil
    for k = 0, 3 do
        local slot = screen + WIDGET.base + k * L.slot_stride
        local b = B.slots[k]
        if b and full then
            if check_button(b) then b.visit = B.visit else b, B.slots[k] = nil, nil end
        end
        if not b and full and u32_at(slot) ~= 0 then
            b = build_button(slot, k)
            if not b then return end
            B.slots[k] = b
            button_note(string.format('Clear buttons: slot %d at %s', k + 1, rect_text(slot)))
        end
        if b then
            local shown, over, gone = false, false, false
            local plate = b.pieces.plate  -- the piece the cursor is tested against: the button's whole square
            if open or k == pad_slot then
                local flags = read(slot + L.widget_flags, 8)
                gone = flags ~= nil and u32(flags, 4) == 0
                shown = flags ~= nil and not gone and bit.band(flags:byte(1), DISABLED_BIT) == 0 and u32_at(plate) ~= 0
                over = open and shown and ui ~= nil and B.fn.hit(ui + L.cursor_widget, plate, 0) ~= 0
            end
            if over and not hovered then hovered = k end
            show_button(b, shown, over and hovered == k, gone)
            if B.highlight then service_highlight(b, slot, over and hovered == k, ui) end
            if shown and B.shown ~= B.visit then
                B.shown = B.visit
                local cursor = ui and read(ui + L.cursor_widget + CURSOR_AT, 8)
                button_note(string.format('Clear buttons: shown; slot %d X at %s; cursor %.1f, %.1f', k + 1,
                                          rect_text(plate), f32(cursor, 0) or 0, f32(cursor, 4) or 0))
            end
        end
    end
    if hovered ~= B.hovered then
        button_note(hovered and string.format('Clear buttons: slot %d X hovered', hovered + 1) or 'Clear buttons: X left')
        B.hovered = hovered
    end
    -- A click: the X hovered now and blocked since the frame before, so the game ignored the press.
    if hovered and B.blocked == hovered and confirm_pressed() then
        clear_slot(screen, index, hovered, 'X clicked')
        B.cleared = {frame = M.frames, k = hovered}
    end
    if hovered then write(screen + L.grid + L.hovered, u32_bytes(0xffffffff)) end
    B.blocked = hovered
end

