local function load_settings()
    local path = settings_path()
    local f = path and (io.open(path, 'rb') or io.open(path .. '.bak', 'rb'))
    if not f then return note('Leave Out: no settings yet (' .. leave_text() .. ')') end
    local text = f:read('*a') or ''
    f:close()
    local pins = 0
    for key, value in text:gmatch('([%w_]+)\t([^\r\n]*)') do
        if key == 'pinned' then
            for id in value:gmatch('%d+') do
                local item = tonumber(id)
                if item and item < 4294967296 and not pinned[item] then pinned[item], pins = true, pins + 1 end
            end
        end
        for k, item in ipairs(LEAVE) do
            if item.key == key then leave[k] = value:sub(1, 1) == '1' end
        end
    end
    note(string.format('Leave Out: %s; %d pinned stratagem(s)', leave_text(), pins))
end

-- Written through <file>.tmp, the old file kept as <file>.bak until the new one is in place.
local function save_settings()
    local path = settings_path()
    if not path then return note('Leave Out: no folder for the settings') end
    local lines, ids = {}, {}
    for k, item in ipairs(LEAVE) do lines[k] = item.key .. '\t' .. (leave[k] and '1' or '0') end
    for item in pairs(pinned) do ids[#ids + 1] = item end
    table.sort(ids)
    for k, item in ipairs(ids) do ids[k] = string.format('%d', item) end
    lines[#lines + 1] = 'pinned\t' .. table.concat(ids, ',')
    local temp, backup = path .. '.tmp', path .. '.bak'
    local f = io.open(temp, 'wb')
    local ok = f and f:write(table.concat(lines, '\n') .. '\n') and f:close()
    if not ok then
        if f then pcall(f.close, f) end
        os.remove(temp)
        return note('Leave Out: the settings could not be written')
    end
    os.remove(backup)
    local moved = os.rename(path, backup)
    if os.rename(temp, path) then
        os.remove(backup)
    else
        if moved then os.rename(backup, path) end
        os.remove(temp)
        note('Leave Out: the settings could not be replaced')
    end
end

