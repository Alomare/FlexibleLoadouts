-- Makes toggle k's button under the equipment slot, centred on its top edge: a plate of the game's fill, the REMOVE
-- label, the box at the plate's right end (the game's cross or check; a square of the fill when they are not loaded).
-- Returns it, or nil after toggle_fail().
local function build_toggle(slot, k)
    local t = {slot = slot, k = k, visit = toggles.visit, pieces = {}, cache = {}, visible = false, unhovered = false,
               checked = nil}
    local fn, lf = buttons.fn, toggles.fn
    local text = T.upper(tr('button.remove'))
    -- The label keeps the string's pointer: its buffer is kept for the session, like the widgets.
    local buffer = ffi.new('char[?]', #text + 1, text)
    buttons.keep[#buttons.keep + 1] = buffer
    local i, h = TOGGLE.inset, TOGGLE.height
    local top, mid = {0.5, 1}, -(i + h / 2)  -- the anchor (the slot's top centre), the plate's middle line
    local guess = #text * TOGGLE.font_size * 0.6  -- the plate's width until the label is measured
    local function plate_width(label_w) return TOGGLE.pad + label_w + TOGGLE.gap + TOGGLE.icon + (h - TOGGLE.icon) / 2 end
    -- The box's centre and the label's right end, for a plate of width w centred on the anchor.
    local function box_x(w) return w / 2 - h / 2 end
    local function label_x(w) return box_x(w) - TOGGLE.icon / 2 - TOGGLE.gap end
    t.marks = marks_available()
    local square = TOGGLE.icon * 0.6
    local plan = {
        {name = 'plate', material = GUI_FILL, w = plate_width(guess), h = h, anchor = top, pivot = {0.5, 1}, x = 0,
         y = -i, layer = TOGGLE.layer},
        {name = 'box', material = t.marks and CHECK_NO or GUI_FILL, w = t.marks and TOGGLE.icon or square,
         h = t.marks and TOGGLE.icon or square, anchor = top, pivot = {0.5, 0.5}, x = box_x(plate_width(guess)), y = mid,
         layer = TOGGLE.layer + 1},
    }
    t.pieces.plate, t.pieces.box, t.pieces.label = allocate(WIDGET_SIZE), allocate(WIDGET_SIZE), allocate(TOGGLE.label_size)
    for _, at in pairs(t.pieces) do t.cache[at] = {} end
    local ok = in_slot_context(slot, 'Leave Out buttons', toggle_fail, function(context)
        for _, p in ipairs(plan) do make_picture(t.pieces[p.name], context, p) end
        -- The label as the game makes its titles here: the #COUNT text with the mod's string, font 4, right-aligned
        -- (pivot (1, 0.5)) just left of the box. Its size comes from its text (the game's layout).
        local at = t.pieces.label
        lf.label_init(at)
        if pointer_at(at + L.widget_context) ~= context then error('the label is not in the slot context') end
        lf.set_label(at, TOGGLE.count_template)
        lf.set_string_arg(at, L.text_count_key, buffer)
        fn.anchor_set(at, pair(top[1], top[2]))
        fn.pivot_set(at, pair(1, 0.5))
        fn.position_set(at, pair(label_x(plate_width(guess)), mid))
        lf.font_set(at, L.title_font, 0, 0, 1, 0)
        lf.font_size_set(at, TOGGLE.font_size)
        fn.layer_set(at, TOGGLE.layer + 1)
        fn.opacity_set(at, 0)
        attach_pieces(slot, t.pieces, {'plate', 'box', 'label'})
        lf.children_refresh(slot)
    end)
    if not ok then return nil end
    -- The plate fitted to the label's measured width (the game's layout of the label, run now), the box and the
    -- label placed on it again.
    lf.measure(t.pieces.label)
    local size = read(t.pieces.label + TOGGLE.label_width, 8)
    local label_w = f32(size, 0)
    local measured = label_w and label_w >= 1 and label_w < 400
    local w = plate_width(measured and label_w or guess)
    fn.size_set(t.pieces.plate, pair(w, h))
    fn.position_set(t.pieces.box, pair(box_x(w), mid))
    fn.position_set(t.pieces.label, pair(label_x(w), mid))
    toggles.made = toggles.made + 1
    button_note(string.format('Leave Out buttons: %s button made (%s; label "%s" %s; font size read %.1f; '
                              .. '%d made this session)', LEAVE[k].text,
                              t.marks and 'the check and cross' or 'a square box', text,
                              measured and string.format('%.1f x %.1f units', label_w, f32(size, 4) or 0)
                              or ('not measured (' .. tostring(label_w) .. '), sized by a guess'),
                              f32(read(t.pieces.label + L.label_font_size, 4), 0) or -1, toggles.made))
    return t
end

-- A full check, as for the X's: every piece alive, under the slot and in its child list; else dropped (this visit's
-- orphan destroyed, an older one forgotten).
local function check_toggle(t)
    local lost = nil
    for name, at in pairs(t.pieces) do
        if u32_at(at) == 0 then lost = lost or (name .. ' torn down')
        elseif pointer_at(at + L.widget_parent) ~= t.slot then lost = lost or (name .. ' has another parent')
        elseif not is_child(t.slot, at) then lost = lost or (name .. " not in the slot's children") end
    end
    if not lost then return true end
    local destroy = t.visit == toggles.visit
    button_note(string.format('Leave Out buttons: %s button lost (%s); %s', LEAVE[t.k].text, lost,
                              destroy and 'destroying its pieces' or 'forgotten (an earlier visit)'))
    if destroy then
        for _, at in pairs(t.pieces) do
            if u32_at(at) ~= 0 then buttons.fn.destroy(at) end
        end
    end
    return false
end

-- Shows a toggle or hides it (the game's fade on a change), hovered or not, checked or not.
local function show_toggle(t, shown, hovered)
    local p, fn = t.pieces, buttons.fn
    if shown ~= t.visible then
        t.visible = shown
        for _, name in ipairs({'plate', 'box', 'label'}) do
            local at = p[name]
            if u32_at(at) ~= 0 then
                local alpha = name == 'plate' and BUTTON.plate_alpha or 1
                if buttons.fade then
                    fn.fade(at, shown and 0 or 1, shown and BUTTON.fade_in or BUTTON.fade_out, alpha, 0)
                else
                    fn.opacity_set(at, shown and alpha or 0)
                end
            end
        end
    end
    local checked = leave[t.k]
    if checked ~= t.checked and t.marks and u32_at(p.box) ~= 0 then
        fn.material_set(p.box, checked and TOGGLE.check_yes or CHECK_NO, 0)
    end
    t.checked = checked
    set_colour(t, p.plate, hovered and BUTTON.plate_hover or BUTTON.plate)
    set_colour(t, p.box, checked and TOGGLE.checked or TOGGLE.grey)
    set_colour(t, p.label, hovered and TOGGLE.text_hover or TOGGLE.text)
end

-- The slot under a hovered toggle looks unhovered: the game's redraw with the slot's hover bit cleared for the call
-- (its unhovered look: grey, or the focus yellow), the bit set back after (the game keeps hit-testing the slot, which
-- holds the button, so it never sees a change: no sound, no redraw of its own). Again whenever the game redrew it
-- white meanwhile. Off the toggle, the game's redraw once (the slot's own look for its bit).
local function service_slot_look(t, on_toggle)
    local slot = t.slot
    if on_toggle then
        local flags = read(slot + L.vr_flags, 2)
        local colour = read(slot + toggles.frame_colour, 12)
        local white = colour and f32(colour, 0) > TOGGLE.white and f32(colour, 4) > TOGGLE.white and f32(colour, 8) > TOGGLE.white
        if flags and bit.band(flags:byte(1), 1) ~= 0 and (white or not t.unhovered) then
            write(slot + L.vr_flags, string.char(bit.band(flags:byte(1), 0xfe), flags:byte(2)))
            toggles.redraw(slot)
            write(slot + L.vr_flags, flags)
            if not t.unhovered then
                button_note(string.format('Leave Out buttons: %s slot unhovered under its button', LEAVE[t.k].text))
            end
        end
        t.unhovered = true
    elseif t.unhovered then
        t.unhovered = false
        if u32_at(slot) ~= 0 then toggles.redraw(slot) end
    end
end

-- The toggles' gates: the common ones in the equipment view (mode 1), the view active and settled (its transition
-- byte clear). Returns whether a click is taken, whether the view shows at all (a checked toggle stays in sight), and
-- the toggle to mark when only mouse mode fails: with a controller the focused weapon slot's toggle shows (no click).
local function toggle_gates(screen, list_open)
    local why, mode = common_gates(screen, list_open)
    local view_shown = not list_open and mode == 1 and u8_at(screen + toggles.transition) == 0
    if why and why ~= 'not mouse mode' then
    elseif mode ~= 1 then why = 'the stratagems shown'
    elseif u8_at(screen + toggles.view + L.view_active) == 0 then why = 'view inactive'
    elseif not view_shown then why = 'view changing' end
    local pad_slot = nil
    if why == 'not mouse mode' then
        local focus = i32(u32_at(screen + toggles.view + L.view_focus))
        if focus and focus >= 3 and focus <= 5 then pad_slot = focus - 2 end
    end
    local text = (why and ('no click (' .. why .. ')') or 'taking clicks') .. (view_shown and '' or ', hidden')
                 .. (pad_slot and (', ' .. LEAVE[pad_slot].text .. ' marked') or '')
    if text ~= toggles.gates then
        toggles.gates = text
        button_note('Leave Out buttons: ' .. text)
    end
    return why == nil, view_shown, pad_slot
end

-- The key on weapon slot k: its toggle flipped, as a click on it.
function flip_toggle(k)
    set_leave(k, not leave[k])
    buttons.fn.sound(0, TOGGLE.sound)
end

-- Each frame on the loadout screen: per weapon slot its toggle (made and fully checked every few frames), shown,
-- hovered, checked; a click toggles it.
function service_toggles(screen, list_open)
    local G = toggles
    if G.failed then return end
    if G.screen ~= screen then G.screen, G.slots = screen, {} end
    local full = M.frames % CHECK_EVERY == 0 or G.checked ~= G.visit
    G.checked = G.visit
    local open, view_shown, pad_slot = toggle_gates(screen, list_open)
    local ui = buf_pointer(buffers.global, 0)
    local hovered = nil
    for k = 1, 3 do
        local slot = screen + G.slots_at[k]
        local t = G.slots[k]
        if t and full then
            if check_toggle(t) then t.visit = G.visit else t, G.slots[k] = nil, nil end
        end
        if not t and full and view_shown and u32_at(slot) ~= 0 then
            t = build_toggle(slot, k)
            if not t then return end
            G.slots[k] = t
            button_note(string.format('Leave Out buttons: %s slot at %s', LEAVE[k].text, rect_text(slot)))
        end
        if t then
            local alive = u32_at(t.pieces.plate) ~= 0
            local shown = alive and view_shown and (open or leave[k] or k == pad_slot)
            local over = shown and open and ui ~= nil and buttons.fn.hit(ui + L.cursor_widget, t.pieces.plate, 0) ~= 0
            if over and not hovered then hovered = k end
            show_toggle(t, shown, over and hovered == k)
            service_slot_look(t, over and hovered == k)
            if shown and t.logged ~= G.visit then
                t.logged = G.visit
                button_note(string.format('Leave Out buttons: %s shown at %s', LEAVE[k].text, rect_text(t.pieces.plate)))
            end
        end
    end
    if hovered ~= G.hovered then
        button_note(hovered and string.format('Leave Out buttons: %s hovered', LEAVE[hovered].text)
                    or 'Leave Out buttons: left')
        if hovered then buttons.fn.sound(0, TOGGLE.hover_sound) end
        G.hovered = hovered
    end
    if G.changed and G.changed.frame == M.frames - 1 then
        button_note(list_open and 'Leave Out buttons: THE LIST OPENED after a click' or 'Leave Out buttons: no list after the click')
        G.changed = nil
    end
    -- A click: the toggle hovered now and blocked since the frame before, so the game ignored the press.
    if hovered and G.blocked == hovered and confirm_pressed() then
        flip_toggle(hovered)
        G.changed = {frame = M.frames, k = hovered}
    end
    if hovered then write(screen + G.view + L.view_hovered, u32_bytes(0xffffffff)) end
    G.blocked = hovered
end
end

