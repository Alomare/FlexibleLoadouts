-- mode 1). Made like the X's: the game's own widgets under the slot, in its GUI context, faded in and out the game's
-- way. Checked (the game's check, tinted the X's red) the Helldiver goes without it; unchecked, the game's cross in
-- grey. While a button is hovered the mod writes the view's hovered slot as none (the view's click
-- reads it before the mod's update writes it again), so a click there is the mod's alone. The slot under it is drawn
-- unhovered by the game's own redraw with the hover bit cleared for that call: the view hit-tests its slots every
-- frame, so the bit itself stays as the game set it, and no hover sound plays. A checked button stays in sight while
-- the view shows, also when it takes no click (ready, a controller), so the choice can always be seen.

