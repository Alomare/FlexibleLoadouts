-- Weapons left behind (research: RESEARCH.md, "Weapons left behind")
--
-- Three Leave Out toggles on the Hellpod loadout (the REMOVE buttons): in a mission the local Helldiver goes without
-- its primary, its secondary or its grenades. The loadout stays as it is (the game has no "none" weapon, and teammates
-- are sent the loadout). In the mission the mod asks the game's own weapon selection to put the weapon away (to the
-- other weapon, else the support weapon, else unarmed), then empties its inventory slot, keeping the weapon (logged at
-- a reinforce), and sends teammates the game's own inventory and selection messages, so their copy of the Helldiver
-- has the slot empty too (the game's own way of telling them about an empty support slot). The game itself refuses a
-- switch to an empty slot; resupplies skip it, and where the game goes back to after a throw is kept pointing at the
-- slot the mod switches to. Grenades: the count is set to 0, the game's "out of grenades", again after each refill. Every reinforce brings a new Helldiver, handled the same way. A weapon picked up from the ground
-- is kept. The toggles are kept in FlexibleLoadouts.settings beside the logs, so they last like the loadout does.

local WEAPON_SIGS = {'local_avatar', 'unit_lookup', 'inv_selection', 'throw_count', 'select_request', 'throw_return',
                     'can_switch', 'is_dead', 'health', 'game_state', 'wielder', 'hand_release', 'inv_rpc', 'sel_rpc',
                     'entity_lookup'}
local LEAVE = {{key = 'leave_primary', text = 'primary'}, {key = 'leave_secondary', text = 'secondary'},
               {key = 'leave_grenades', text = 'grenades'}}
local SETTINGS_FILE = 'FlexibleLoadouts.settings'
local INV = {map = 0x28, empty = 0x34, mult = 0x38, stride = 0x30}  -- literal in inv_selection
local ROW = {support = 8, backpack = 0xc, held = 0x10, carried = 0x14, melee = 0x18, throwable = 0x28}
local SLOT_NAMES = {[0] = 'unarmed', 'the primary', 'the secondary', 'the support weapon'}
local HAND_STRIDE = 0x50            -- a wielder's hands (literal in wielder: shl 4 of index * 5)
local ALL_PEERS = -2                -- the game's own target for these messages: every other peer
local MAX_PROBES, MAX_ENTITIES, MAX_INDEX = 64, 262144, 4096
local SETTLED_POLL = 10             -- frames between checks while nothing is pending
local RETRY = 15                    -- frames between repeated selection requests
local GIVE_UP = 600                 -- frames a request may go unanswered before it is logged as stuck
local STRAY_FRAMES = 5              -- frames a weapon not in the row stays in hand before it is released
local TRACE_LINES = 600             -- the recon build's state trace: at most this many lines a session
local WEAPON_FN = {
    request = 'void (*)(int32_t *, int32_t)', can_switch = 'uint8_t (*)(int32_t *)',
    is_dead = 'uint8_t (*)(uint64_t, uint32_t)', entity_event = 'void (*)(uint32_t, uint32_t, uint64_t)',
    inv_rpc = 'void (*)(int64_t, uint32_t, uint32_t, uint32_t, uint32_t, uint32_t, uint32_t, uint64_t)',
    sel_rpc = 'void (*)(int64_t, uint32_t, uint32_t)', entity_lookup = 'uint64_t (*)(uint32_t)',
    release = 'uint32_t (*)(uint64_t, uint32_t, uint32_t, uint32_t)', destroy = 'void (*)(uint64_t, uint32_t)',
}
-- The weapon code's own fields that must equal each other's (or the core's): else the weapon options are off alone.
local WEAPON_SAME = {{'la_avatars', 'cs_avatars'}, {'sr_stride', 'cs_stride'}, {'ul_owner', 'el_owner'},
                     {'la_no_entity', 'is_no_entity'}, {'la_no_entity', 'wd_no_entity'},
                     {'ir_net_record', 'sel_net_record'}, {'ir_send', 'sel_send'}, {'ir_send', 'rpc_send'},
                     {'la_players', 'players'}, {'sr_ctrl', 'tr_ctrl'}, {'sr_request', 'tr_request'},
                     {'is_inventory', 'tr_inventory'}, {'wd_stride', 'hr_stride'}}

local weapons = {fn = nil, entity = nil, kept = {}, pickup = {}, dirty = false, asked_at = nil, waiting = nil,
                 dead = nil, why = nil, logged = false, busy = false, next_check = 0, notes = 0, destroy = false,
                 stray = nil, stray_at = nil, state = nil, traces = 0}
local leave = {false, false, false}  -- the toggles: primary, secondary, grenades
local pinned = {}                    -- the pinned stratagems: item id -> true

local function weapon_note(msg)  -- bounded: no flood when something repeats
    weapons.notes = weapons.notes + 1
    if weapons.notes <= 400 then note(msg) end
end

-- The weapon code: every signature found, the cross-checks, the functions. Sets EXTRA.weapons.
local function read_weapons()
    local found = code.found
    local why = nil
    for _, name in ipairs(WEAPON_SIGS) do
        if not why and not found[name] then why = string.format('code "%s" %s', name, code.missing[name] or 'not found') end
    end
    for _, same in ipairs(WEAPON_SAME) do
        if not why and L[same[2]] ~= nil and L[same[1]] ~= L[same[2]] then
            why = string.format('"%s" differs from "%s"', same[1], same[2])
        end
    end
    if not why and L.la_unit_entity ~= found.unit_lookup then why = 'the local avatar check calls another lookup' end
    -- The controller's previous and last weapon slots: int fields just after its entity and requested slot.
    local previous, last = L.tr_previous and L.tr_previous - L.tr_ctrl, L.tr_last_weapon and L.tr_last_weapon - L.tr_ctrl
    if not why and not (previous and last and previous >= 8 and last >= 8 and previous ~= last and previous < 0x40
                        and last < 0x40 and previous % 4 == 0 and last % 4 == 0) then
        why = 'selection controller layout'
    end
    -- The hand release scans the hands the way the mod reads hand 0: five of them, HAND_STRIDE apart.
    if not why and (L.hr_hand_stride ~= HAND_STRIDE or L.hr_hands ~= 5) then why = 'wielder hand layout' end
    local fn = {}
    if not why then
        local rvas = {request = L.sr_request, can_switch = found.can_switch, is_dead = found.is_dead,
                      entity_event = L.tc_entity_event, inv_rpc = found.inv_rpc, sel_rpc = found.sel_rpc,
                      entity_lookup = found.entity_lookup, release = found.hand_release}
        -- The test key's destroy: the inventory's own destroy-all calling it, with the lookup found.
        weapons.destroy = found.weapon_destroy ~= nil and L.ds_lookup == found.entity_lookup and L.ds_owner == L.ul_owner
                          and L.ds_rows == L.is_rows
        if weapons.destroy then rvas.destroy = L.ds_destroy end
        for short, rva in pairs(rvas) do
            local ok, f = pcall(ffi.cast, WEAPON_FN[short], native.base + rva)
            if ok then fn[short] = f else why = why or ('native function ' .. short .. ' unavailable') end
        end
    end
    if not why then weapons.fn, weapons.previous, weapons.last_weapon = fn, previous, last end
    EXTRA.weapons, EXTRA.weapons_why = not why, why
end

-- Low 32 bits of a * b (both 32-bit), exact in doubles.
local function mul32(a, b)
    local al, ah, bl, bh = a % 65536, math.floor(a / 65536), b % 65536, math.floor(b / 65536)
    return (al * bl + ((ah * bl + al * bh) % 65536) * 65536) % 4294967296
end

-- The game's id maps: rows of (key, value) u32 pairs at [base + map], capacity a power of two, probed linearly from
-- key * mult. Returns the value, or nil and a reason.
local function lookup(base, map, cap, empty, mult, key)
    local data, capacity, empty_key, multiplier
    if cap == map + 8 and empty == map + 12 and mult == map + 16 then  -- the usual layout: one read
        local head = read(base + map, 20)
        data, capacity, empty_key, multiplier = pointer(head), u32(head, 8), u32(head, 12), u32(head, 16)
    else
        data, capacity, empty_key, multiplier = pointer_at(base + map), u32_at(base + cap), u32_at(base + empty),
                                                u32_at(base + mult)
    end
    if not (data and capacity and empty_key and multiplier) then return nil, 'map unreadable' end
    if capacity == 0 then return nil, 'map empty' end
    if capacity > 16777216 or bit.band(capacity, capacity - 1) ~= 0 then return nil, 'map capacity unexpected' end
    local hash = mul32(key, multiplier)
    for probe = 0, math.min(capacity, MAX_PROBES) - 1 do
        local row = read(data + ((hash + probe) % capacity) * 8, 8)
        if not row then return nil, 'map row unreadable' end
        local k = u32(row, 0)
        if k == empty_key then return nil, 'not in map' end
        if k == key then return u32(row, 4) end
    end
    return nil, 'not in map'
end

-- The local Helldiver (the game's own test): {entity, ctrl}, or nil and why.
local function local_avatar()
    local players = global(L.la_players)
    if not players then return nil, 'no players' end
    if u32_at(players + L.la_active) == 0 then return nil, 'no local player' end
    local unit = u32_at(players + L.la_unit)
    if not unit or unit == L.ul_no_unit then return nil, 'no Helldiver (no unit)' end
    local owner = global(L.ul_owner)
    if not owner then return nil, 'no entity owner' end
    local index, why = lookup(owner, L.ul_map, L.ul_cap, L.ul_empty, L.ul_mult, unit)
    if not index then return nil, 'unit: ' .. why end
    if index >= MAX_ENTITIES then return nil, 'entity index unexpected' end
    local entity = u32_at(owner + L.ul_entity_ids * 8 + index * 24)
    if not entity or entity == u32_at(native.base + L.la_no_entity) then return nil, 'no Helldiver (no entity)' end
    local avatars = global(L.la_avatars)
    if not avatars then return nil, 'no avatar manager' end
    local ai
    ai, why = lookup(avatars, L.la_avatar_map, L.la_avatar_cap, L.la_avatar_empty, L.la_avatar_mult, entity)
    if not ai then return nil, 'avatar: ' .. why end
    if ai >= MAX_INDEX then return nil, 'avatar index unexpected' end
    local ctrl = avatars + L.sr_ctrl + ai * L.sr_stride
    -- The request and the switch test index the avatars by the controller's entity: it must be ours.
    if u32_at(ctrl) ~= entity then return nil, 'the selection controller names another entity' end
    return {entity = entity, ctrl = ctrl}
end

-- The Helldiver's inventory row: {at, blob, counts_at, goid}, or nil and why.
local function inventory_row(entity)
    local inv = global(L.is_inventory)
    if not inv then return nil, 'no inventory' end
    local ri, why = lookup(inv, INV.map, L.is_cap, INV.empty, INV.mult, entity)
    if not ri then return nil, 'row: ' .. why end
    if ri >= MAX_INDEX * 16 then return nil, 'row index unexpected' end
    local rows, counts, owners = pointer_at(inv + L.is_rows), pointer_at(inv + L.tc_counts), pointer_at(inv + L.tc_owners)
    local owner = owners and pointer_at(owners + ri * 8)
    if not (rows and counts and owner) then return nil, 'row unreadable' end
    if u32_at(owner + 8) ~= entity then return nil, 'the row names another entity' end
    local at = rows + ri * INV.stride
    local blob = read(at, INV.stride)
    if not blob then return nil, 'row unreadable' end
    return {at = at, blob = blob, counts_at = counts + ri * 8, goid = u32_at(owner + L.tc_goid)}
end

-- The entity in the Helldiver's hand (0: none), or nil.
local function in_hand(entity)
    local wielder = global(L.wd_global)
    if not wielder then return nil end
    local wi = lookup(wielder, L.wd_map, L.wd_cap, L.wd_empty, L.wd_mult, entity)
    local hands = wi and wi < MAX_INDEX and pointer_at(wielder + L.wd_slots)
    return hands and u32_at(hands + wi * L.wd_stride + 0 * HAND_STRIDE)
end

-- Where the Helldiver goes from a weapon left behind: the first weapon it keeps (the primary, the secondary, or one
-- picked up there), else the support weapon, else unarmed.
local function armed_slot(blob)
    for s = 1, 2 do
        if (not leave[s] or weapons.pickup[s] == u32(blob, (s - 1) * 4)) and u32(blob, (s - 1) * 4) ~= 0 then return s end
    end
    return u32(blob, ROW.support) ~= 0 and 3 or 0
end

local function ask(a, slot, why)
    local W = weapons
    if W.asked_at and M.frames - W.asked_at < RETRY then return end
    W.asked_at = M.frames
    weapon_note(string.format('Weapons: asking for %s (%s)', SLOT_NAMES[slot] or tostring(slot), why))
    W.fn.request(ffi.cast('int32_t *', a.ctrl), slot)
end

-- Drops the state of the Helldiver (gone, or a new one): its kept weapons are logged (do they still exist?).
local function forget(why)
    local W = weapons
    if W.entity then
        weapon_note('Weapons: ' .. why)
        for s = 1, 2 do
            if W.kept[s] then
                weapon_note(string.format("Weapons: that Helldiver's kept %s (%d) %s", LEAVE[s].text, W.kept[s],
                                          W.fn.entity_lookup(W.kept[s]) ~= 0 and 'still exists' or 'is gone'))
            end
        end
    end
    W.entity, W.kept, W.pickup, W.dirty = nil, {}, {}, false
    W.asked_at, W.waiting, W.dead, W.logged = nil, nil, nil, false
    W.stray, W.stray_at, W.state = nil, nil, nil
end

-- An entity the row holds anywhere (weapons, backpack, held, carried, melee) or a kept weapon.
local function in_row(blob, e)
    for _, at in ipairs({0, 4, ROW.support, ROW.backpack, ROW.held, ROW.carried, ROW.melee}) do
        if u32(blob, at) == e then return true end
    end
    return e == weapons.kept[1] or e == weapons.kept[2]
end

local function row_text(blob)
    return string.format('primary %d, secondary %d, support %d, backpack %d, held %d, carried %d, selection %d',
                         u32(blob, 0), u32(blob, 4), u32(blob, ROW.support), u32(blob, ROW.backpack),
                         u32(blob, ROW.held), u32(blob, ROW.carried), u32(blob, L.is_selection))
end

-- Each frame in a mission while a toggle is on and something is pending; every few frames once settled.
local function service_weapons()
    local W = weapons
    if not (leave[1] or leave[2] or leave[3]) then return end
    if not W.busy and M.frames < W.next_check then return end
    W.next_check = M.frames + SETTLED_POLL
    W.busy = false
    local game = global(L.gs_game)
    local game_state = game and u32_at(game + L.gs_state)
    if game_state ~= L.gs_mission then return forget('out of the mission (game state ' .. tostring(game_state) .. ')') end
    local a, why = local_avatar()
    if not a then
        if why ~= W.why then W.why = why; weapon_note('Weapons: ' .. why) end
        return forget('no Helldiver')
    end
    W.why = nil
    if a.entity ~= W.entity then
        forget('another Helldiver')
        W.entity = a.entity
        weapon_note(string.format('Weapons: Helldiver %d', a.entity))
    end
    local health = global(L.health_global)
    if not health then return end
    if W.fn.is_dead(health, a.entity) ~= 0 then
        if not W.dead then W.dead = true; weapon_note('Weapons: the Helldiver is dead') end
        return
    end
    local r
    r, why = inventory_row(a.entity)
    if not r then
        if why ~= W.why then W.why = why; weapon_note('Weapons: ' .. why) end
        return
    end
    local blob = r.blob
    if not W.logged then
        W.logged = true
        weapon_note('Weapons: row ' .. row_text(blob))
    end
    local selection = u32(blob, L.is_selection)
    local free = u32(blob, ROW.held) == 0 and u32(blob, ROW.carried) == 0  -- no grenade, stratagem or object in hand
    local hand = in_hand(a.entity)
    local can = nil
    local function may_switch()
        if can == nil then can = W.fn.can_switch(ffi.cast('int32_t *', a.ctrl)) ~= 0 end
        return can
    end
    -- Recon trace: the selection, the controller's slots (requested at +4), the hand, what is held and whether a
    -- switch is allowed, logged on each change (at the check's pace: every 10 frames once settled).
    if W.traces < TRACE_LINES then
        local state = string.format('selection %d, requested %s, previous %s, last weapon %s, hand %s, held %d, '
                                    .. 'carried %d, switch %s', selection, tostring(u32_at(a.ctrl + 4)),
                                    tostring(u32_at(a.ctrl + W.previous)), tostring(u32_at(a.ctrl + W.last_weapon)),
                                    tostring(hand), u32(blob, ROW.held), u32(blob, ROW.carried),
                                    may_switch() and 'allowed' or 'not allowed')
        if state ~= W.state then
            W.state, W.traces = state, W.traces + 1
            note('Weapons: state ' .. state)
        end
    end
    for s = 1, 2 do
        local e = u32(blob, (s - 1) * 4)
        if leave[s] then
            if e ~= 0 and W.kept[s] and e ~= W.kept[s] and W.pickup[s] ~= e then
                W.pickup[s] = e
                weapon_note(string.format('Weapons: a %s picked up (%d): kept', LEAVE[s].text, e))
            end
            if e ~= 0 and W.pickup[s] ~= e then
                if selection == s or hand == e then
                    W.busy = true
                    if free and may_switch() then ask(a, armed_slot(blob), 'leaving ' .. SLOT_NAMES[s]) end
                    W.waiting = W.waiting or M.frames
                    if M.frames - W.waiting == GIVE_UP then
                        weapon_note(string.format('Weapons: %s still in hand after %d frames (selection %d, hand %s)',
                                                  SLOT_NAMES[s], GIVE_UP, selection, tostring(hand)))
                    end
                else
                    write(r.at + (s - 1) * 4, u32_bytes(0))
                    W.kept[s], W.dirty, W.busy, W.waiting = e, true, true, nil
                    weapon_note(string.format('Weapons: %s left behind (%d; selection %d, hand %s)', LEAVE[s].text, e,
                                              selection, tostring(hand)))
                end
            elseif e == 0 and selection == s then
                -- The game selected the empty slot itself (ledges, objectives): back to the fallback.
                W.busy = true
                if free and may_switch() then ask(a, armed_slot(blob), SLOT_NAMES[s] .. ' selected while empty') end
            end
        end
    end
    -- The way back after a throw: the game asks for the controller's previous slot after a stratagem, its last weapon
    -- slot after the last grenade, as they are. It refuses an empty slot there, which left the Helldiver in the throw
    -- pose with the stratagems locked. A weapon slot named there that is empty becomes the slot the mod switches to.
    if leave[1] or leave[2] then
        for _, field in ipairs({{'previous', W.previous}, {'last weapon', W.last_weapon}}) do
            local slot = u32_at(a.ctrl + field[2])
            if slot and slot >= 1 and slot <= 3 and u32(blob, (slot - 1) * 4) == 0 then
                local to = armed_slot(blob)
                write(a.ctrl + field[2], u32_bytes(to))
                weapon_note(string.format("Weapons: the controller's %s slot was %s, empty: now %s", field[1],
                                          SLOT_NAMES[slot], SLOT_NAMES[to]))
            end
        end
    end
    -- A weapon dropped with nothing to switch to (the support weapon, a weapon left out): the game's drop empties its
    -- slot and selects unarmed, then asks for the previous slot or the primary, refused when empty, so nothing takes
    -- over the hand and the dropped weapon stays wielded (it fires from the ground). One in hand for a few frames that
    -- the row no longer holds is released with the game's own hand release (as the drop calls it), then the fallback
    -- asked for when it is a weapon.
    local stray = (leave[1] or leave[2]) and free and selection <= 3 and hand and hand ~= 0
                  and hand ~= u32_at(native.base + L.la_no_entity) and not in_row(blob, hand)
                  and W.fn.entity_lookup(hand) ~= 0 and hand
    if not stray then
        W.stray, W.stray_at = nil, nil
    elseif stray ~= W.stray then
        W.stray, W.stray_at, W.busy = stray, M.frames, true
    elseif M.frames - W.stray_at < STRAY_FRAMES then
        W.busy = true
    else
        local got = W.fn.release(0, a.entity, stray, 0)
        local after = in_hand(a.entity)
        W.stray, W.stray_at, W.busy = nil, nil, true
        weapon_note(string.format('Weapons: %d in hand, not in the row (selection %d): released (hand %s; now %s)',
                                  stray, selection, got == 0xFFFFFFFF and 'not found' or tostring(got), tostring(after)))
        local to = armed_slot(blob)
        if to ~= 0 and selection == 0 and may_switch() then ask(a, to, 'after a drop') end
    end
    -- Teammates: the game's own inventory message with the row as it is now, then the selection (once per change,
    -- only while the Helldiver could switch and holds nothing else).
    if W.dirty then
        W.busy = true
        if free and selection <= 3 and may_switch() then
            local now = read(r.at, INV.stride)
            if now then
                W.fn.inv_rpc(ALL_PEERS, a.entity, u32(now, 0), u32(now, 4), u32(now, ROW.support), u32(now, ROW.backpack),
                             u32(now, ROW.melee), ffi.cast('uint64_t *', ffi.cast('const char *', now) + ROW.throwable)[0])
                W.fn.sel_rpc(ALL_PEERS, a.entity, u32(now, L.is_selection))
                W.dirty = false
                weapon_note('Weapons: teammates sent the row (' .. row_text(now) .. ')')
            end
        end
    end
    -- Grenades: the count at 0 (again after each refill), posted the game's way so the HUD follows.
    local count = u32_at(r.counts_at)
    if leave[3] and count and count > 0 then
        W.busy = true
        if selection == 4 then
            -- A grenade in hand: put it back first (the game returns it to the count).
            if may_switch() then ask(a, armed_slot(blob), 'a grenade in hand') end
        else
            write(r.counts_at, u32_bytes(0))
            W.fn.entity_event(r.goid, L.tc_event, r.counts_at)
            weapon_note(string.format('Weapons: grenades left behind (%d)', count))
        end
    end
end

