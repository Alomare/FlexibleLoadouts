        if u32_at(at) == 0 then lost = lost or (name .. ' torn down')
        elseif pointer_at(at + L.widget_parent) ~= r.slot then lost = lost or (name .. ' has another parent')
        elseif not is_child(r.slot, at) then lost = lost or (name .. " not in the widget's children") end
    end
    if lost and r.visit == visit then
        for _, at in pairs(r.pieces) do
            if u32_at(at) ~= 0 then buttons.fn.destroy(at) end
        end
    end
    return lost
end

