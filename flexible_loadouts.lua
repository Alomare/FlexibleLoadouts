    read_toggles()
    pins.read()
    dice.read()
    if not (EXTRA.ready or EXTRA.advance or EXTRA.clear or EXTRA.weapons) then
        return unavailable(tostring(EXTRA.ready_why))
    end
    if not EXTRA.buttons then note('Clear buttons not available: ' .. tostring(EXTRA.buttons_why)) end
    if not EXTRA.weapons then note('Weapons left behind not available: ' .. tostring(EXTRA.weapons_why)) end
    if not EXTRA.toggles then note('Leave Out buttons not available: ' .. tostring(EXTRA.toggles_why)) end
    if not EXTRA.pins then note('Pinned stratagems not available: ' .. tostring(EXTRA.pins_why)) end
    if not EXTRA.dice then note('Randomize Lineup not available: ' .. tostring(EXTRA.dice_why)) end
    if not EXTRA.ready then note('Ready with empty slots not available: ' .. tostring(EXTRA.ready_why)) end
    if EXTRA.ready and not EXTRA.press then note('Ready press check not available: ' .. tostring(EXTRA.press_why)) end
    if EXTRA.ready and not EXTRA.emote then note('Ready pose not available: ' .. tostring(EXTRA.emote_why)) end
    if not EXTRA.advance then note('List kept open not available: ' .. tostring(EXTRA.advance_why)) end
    for _, k in ipairs({'scroll', 'clear'}) do
        if not EXTRA[k] then note(k .. ' not available: ' .. tostring(EXTRA[k .. '_why'])) end
    end
    make_buffers()
    if EXTRA.weapons or EXTRA.pins then load_settings() end
    where_found = #code.moved == 0 and "at this game version's addresses"
                  or ('by search (' .. #code.moved .. ' moved: ' .. table.concat(code.moved, ', ') .. ')')
    note('Game code found ' .. where_found)
    state.ready = true
    -- The game's Text Language, for this mod's texts and every other mod's (bingus_text's shared registry).
    local tag, game_code = T.observe(read, native.base)
    note('Text language: ' .. tostring(T.language()) .. ' (game setting ' .. tostring(game_code or 'unreadable')
         .. ', tag ' .. tostring(tag) .. ')')
    report()
end

local function start()
    local ok, why = init_native()
    if not ok then
        write_status('NOT AVAILABLE - ' .. why .. '; the loadout works as normal')
        M.retired = true
        return
    end
    code = sigscan.new(SIGS, read, native.base)
    local all, reason = code:start()
    if all == nil then return unavailable(reason) end
    if all then return finish_start() end
    note('Searching game.dll for moved code')
end

local function frame(dt)
    M.frames = M.frames + 1
    M.time = M.time + (tonumber(dt) or 0)
    if M.frames == 1 then
        start()
    elseif code and code.scan then
        if code:step() then finish_start() end
    elseif state.ready then
        step()
    end
end

local original_update = rawget(_G, 'update')
update = function(dt, ...)
    if not M.retired then
        local ok, err = xpcall(frame, debug.traceback, dt)
        if not ok then
            M.errors = M.errors + 1
            note('Error: ' .. tostring(err))
            if M.errors >= 5 then
                M.retired = true
                write_status('STOPPED - repeated errors; the loadout works as normal (see FlexibleLoadouts.log)')
            end
        end
    end
    if type(original_update) == 'function' then return original_update(dt, ...) end
end

