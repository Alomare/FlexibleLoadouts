-- Each group's pinned stratagems first (in the game's order), then the others in the game's order. Written only
-- when that changes the list; then the page cache cleared, the game's layout, the focus put back on its stratagem
-- and the details panel told (as the game does after a focus change).
function H.apply_order(screen, list, n, why)
    H.restore_byte(list)
    local groups = u32_at(list + L.lg_count)
    local starts = groups and groups >= 1 and groups <= 64 and read(list + L.lg_start, groups * 4)
    if not starts then return H.pin_note('Pins: the list groups are unreadable (' .. tostring(groups) .. ')') end
    local vanilla, order, keys = pins.vanilla, {}, {}
    for g = 0, groups - 1 do
        local a, b = u32(starts, g * 4), g + 1 < groups and u32(starts, (g + 1) * 4) or n
        if not a or not b or a > b or b > n then return H.pin_note('Pins: the list groups do not fit the list') end
        keys[#keys + 1] = string.format('%d-%d', a, b - 1)
        for i = a + 1, b do if H.is_pinned(vanilla[i]) then order[#order + 1] = vanilla[i] end end
        for i = a + 1, b do if not H.is_pinned(vanilla[i]) then order[#order + 1] = vanilla[i] end end
    end
    if #order ~= n then return H.pin_note('Pins: the groups do not cover the list') end
    local same = true
    for i = 1, n do if order[i] ~= pins.ids[i] then same = false; break end end
    if not pins.logged then
        pins.logged = true
        H.pin_note(string.format('Pins: list of %d in %d group(s) (%s); %d pinned', n, groups, table.concat(keys, ', '),
                               H.pinned_count()))
    end
    if same then return end
    local sel, byte2 = read(list + L.selectable, n), read(list + L.lg_byte2, n)
    if not sel or not byte2 then return H.pin_note('Pins: the list bytes are unreadable') end
    local sel_of, byte2_of = {}, {}
    for i, offer in ipairs(pins.ids) do sel_of[offer], byte2_of[offer] = sel:sub(i, i), byte2:sub(i, i) end
    local out_ids, out_sel, out_byte2 = {}, {}, {}
    for i, offer in ipairs(order) do
        out_ids[i], out_sel[i], out_byte2[i] = u32_bytes(offer), sel_of[offer], byte2_of[offer]
    end
    local focused = u32_at(list + L.lf_offer)
    local blob = table.concat(out_ids)
    write(list + L.ids, blob)
    write(list + L.selectable, table.concat(out_sel))
    write(list + L.lg_byte2, table.concat(out_byte2))
    write(list + L.lc_cache, string.rep('\255', 4 * pins.pages))
    native.layout(list)
    if focused and focused ~= 0 and pins.pos[focused] then
        native.list_focus(list, focused)
        pins.fn.preview(screen + L.list_grid)
    end
    pins.written, pins.scan = blob, nil
    H.set_order(order)
    H.pin_note(string.format('Pins: list reordered (%s; focus %s)', why, focused and string.format('%x', focused) or '-'))
end

-- The list's cells in use: {cell, offer, page, col}, from the pages shown (each page a row of cells).
function H.scan_cells(list)
    local cells = {}
    local used = u32_at(list + L.lc_pages)
    if not used or used > pins.pages then return cells end
    for p = 0, used - 1 do
        local count = u32_at(list + L.lc_page_cells + p * L.lc_page_stride) or 0
        for c = 0, math.min(count, H.PIN.columns) - 1 do
            local cell = list + L.lc_cell0 + p * L.lc_page_stride + c * L.lc_cell_stride
            local offer = u32_at(cell + L.lc_offer)
            if offer and offer ~= 0 then cells[#cells + 1] = {cell = cell, offer = offer, page = p, col = c} end
        end
    end
    return cells
end

-- The hovered stratagem's offer (the game's hovered page and its column), or nil.
function H.hovered_offer(list)
    local page = i32(u32_at(list + L.lp_hover_page))
    if not page or page < 0 or page >= pins.pages then return nil end
    local col = i32(u32_at(list + L.lp_hover_col + page * L.lc_page_stride))
    if not col or col < 0 or col >= H.PIN.columns then return nil end
    local offer = u32_at(list + L.lc_cell0 + page * L.lc_page_stride + col * L.lc_cell_stride + L.lc_offer)
    return offer ~= 0 and offer or nil
end

-- The list takes a click on a cell: the screen's own input gates (the list's input runs behind them), the list in
-- its normal state, mouse mode. Returns nil (all pass) or the first that fails.
H.SCREEN_GATES = {launching = true, input_delay = true, busy_a = true, busy_b = true, busy_c = true, state_a = true,
                  state_b = true}

-- Mouse mode as the list's press reads it: the mouse byte set and the pad byte (right after it) clear.
function H.mouse_mode()
    local input = global(L.click_input)
    local modes = input and read(input + L.mouse_mode, 2)
    return modes ~= nil and modes:byte(1) ~= 0 and modes:byte(2) == 0
end

function H.list_gates(screen)
    local v = {}
    for _, g in ipairs(buttons.groups) do
        local wanted = false
        for _, n in ipairs(g.names) do wanted = wanted or H.SCREEN_GATES[n] == true end
        if wanted then
            local blob = read(screen + g.lo, g.size)
            if not blob then return 'unreadable' end
            for _, n in ipairs(g.names) do v[n] = blob:sub(L[n] - g.lo + 1, L[n] - g.lo + 4) end
        end
    end
    local grid = screen + L.list_grid
    if v.launching:byte(1) ~= 0 then return 'launching'
    elseif (f32(v.input_delay, 0) or 1) > 0 then return 'input delay'
    elseif v.busy_a:byte(1) ~= 0 or v.busy_b:byte(1) ~= 0 or v.busy_c:byte(1) ~= 0 then return 'busy'
    elseif not STATE_A[u32(v.state_a)] or not STATE_B[u32(v.state_b)] then return 'state'
    elseif u32_at(grid + L.lu_state) ~= 0 or u8_at(grid + L.lu_panel) ~= 0 then return 'list busy' end
    if not H.mouse_mode() then return 'not mouse mode' end
    return nil
end

function H.toggle_pin(screen, list, n, offer, why)
    local item = H.items()[offer]
    if not item then return H.pin_note(string.format('Pins: offer %x has no stratagem', offer)) end
    pinned[item] = (not pinned[item]) or nil
    H.pin_note(string.format('Pins: %x %s (%s; %d pinned)', item, pinned[item] and 'pinned' or 'unpinned', why,
                           H.pinned_count()))
    save_settings()
    buttons.fn.sound(0, H.PIN.sound)
    H.apply_order(screen, list, n, pinned[item] and 'pinned' or 'unpinned')
end

-- The list open on the stratagems, built: its size (else nil).
function H.open_list(screen)
    if u8_at(screen + L.list_open) == 0 or u32_at(screen + L.category) ~= STRATAGEMS then return nil end
    local n = u32_at(screen + L.list + L.list_count)
    return n and n > 0 and n <= LIST_MAX and n or nil
end

-- The Action key with the list open: the hovered (mouse) else focused stratagem pinned or unpinned.
function pins.key(screen)
    local n = H.open_list(screen)
    if not n or pins.failed then return note('Key: nothing (the list is not on the stratagems)') end
    local list = screen + L.list
    local why = H.list_gates(screen)
    if why and why ~= 'not mouse mode' then return note('Key: nothing (' .. why .. ')') end
    local offer = (not why and H.hovered_offer(list)) or u32_at(list + L.lf_offer)
    note(string.format('Key: the list, %s, hovered %s, focused %s', why and 'controller' or 'mouse',
                       tostring(H.hovered_offer(list)), tostring(u32_at(list + L.lf_offer))))
    if not offer or offer == 0 or not pins.pos or not pins.pos[offer] then return note('Key: no stratagem there') end
    H.toggle_pin(screen, list, n, offer, 'key')
end

-- Each frame on the loadout screen: with the stratagem list open, a new build reordered, then the pins shown on the
-- pinned, hovered and focused stratagems; a click on a hovered pin toggles it.
function pins.service(screen)
    local P = pins
    if P.failed then return end
    if P.screen ~= screen then P.screen, P.cells, P.written = screen, {}, nil end
    local list = screen + L.list
    local n = H.open_list(screen)
    if not n then
        -- Closed (the next opening builds the list again): pins hidden at once, nothing to restore.
        if P.written then
            P.written, P.ids, P.pos, P.vanilla, P.scan, P.restore, P.hovered, P.blocked = nil, nil, nil, nil, nil, nil, nil, nil
            for _, r in pairs(P.cells) do
                if r.visible then H.show_mark(r, false, BUTTON.plate, H.PIN.grey) end
            end
        end
        return
    end
    local blob = read(list + L.ids, n * 4)
    if not blob then return end
    if blob ~= P.written then
        -- A new build, in the game's order: kept as such, then the pins first.
        P.restore, P.written, P.vanilla = nil, blob, {}
        for i = 1, n do P.vanilla[i] = u32(blob, (i - 1) * 4) end
        H.set_order(P.vanilla)
        H.apply_order(screen, list, n, 'list built')
        P.scan = nil
    end
    local full = M.frames % CHECK_EVERY == 0 or P.checked ~= P.visit
    P.checked = P.visit
    local first = u32_at(list + L.lc_first_row)
    if not P.scan or full or first ~= P.first_row then P.scan, P.first_row = H.scan_cells(list), first end
    -- The gates only when they matter: a stratagem hovered with the mouse, or a controller (its focus marked).
    local mouse_mode = H.mouse_mode()
    local over_cell = mouse_mode and H.hovered_offer(list) or nil
    local why = 'nothing hovered'
    if over_cell or not mouse_mode then why = H.list_gates(screen) end
    local mouse = why == nil
    local pad = why == 'not mouse mode'
    local hovered = mouse and over_cell or nil
    local focused = pad and u32_at(list + L.lf_offer) or nil
    local ui = buf_pointer(buffers.global, 0)
    if P.marks == nil then P.marks = H.loaded(H.PIN.name, 'Pins') end
    local over, seen = nil, {}
    for _, c in ipairs(P.scan) do
        local r = P.cells[c.cell]
        if r and full then
            local lost = H.lost_mark(r, P.visit)
            if lost then
                H.pin_note(string.format('Pins: the pin on cell %x lost (%s)', c.cell, lost))
                r, P.cells[c.cell] = nil, nil
            else
                r.visit = P.visit
            end
        end
        local pinned_here = H.is_pinned(c.offer)
        local wanted = pinned_here or (hovered ~= nil and c.offer == hovered) or (focused ~= nil and c.offer == focused)
        if not r and wanted and u32_at(c.cell) ~= 0 then
            r = H.build_mark(c.cell, 'Pins', H.pin_fail, {anchor = {1, 1}, x = H.PIN.centre, y = H.PIN.centre,
                                                       size = H.PIN.size, icon = H.PIN.icon, layer = H.PIN.layer},
                           H.PIN.material, P.marks)
            if not r then return end
            r.visit = P.visit
            P.cells[c.cell] = r
        end
        if r then
            seen[c.cell] = true
            local on = wanted and mouse and c.offer == hovered and u32_at(r.pieces.plate) ~= 0 and ui ~= nil
                       and buttons.fn.hit(ui + L.cursor_widget, r.pieces.plate, 0) ~= 0
            if on then over = c.offer end
            local mark = pinned_here and (on and H.PIN.yellow_hover or H.PIN.yellow) or (on and H.PIN.grey_hover or H.PIN.grey)
            H.show_mark(r, wanted, on and BUTTON.plate_hover or BUTTON.plate, mark)
        end
    end
    for cell, r in pairs(P.cells) do
        if not seen[cell] and r.visible then H.show_mark(r, false, BUTTON.plate, H.PIN.grey) end
    end
    if over ~= P.hovered then
        H.pin_note(over and string.format('Pins: pin hovered (%x)', over) or 'Pins: pin left')
        P.hovered = over
    end
    -- A click: the pin hovered now and blocked since the frame before, so the game refused the press.
    if over and P.blocked == over and confirm_pressed() then
        H.toggle_pin(screen, list, n, over, 'pin clicked')
        over = nil
    end
    -- While a pin is hovered its cell takes no click: the selectable byte 0 (the game's own "can't pick").
    if P.restore and P.restore.offer ~= over then H.restore_byte(list) end
    if over and P.pos[over] then
        local at = list + L.selectable + P.pos[over]
        if not P.restore then P.restore = {offer = over, byte = u8_at(at) or 1} end
        write(at, '\0')
    end
    P.blocked = over
end

