-- HD2-Addon: mods/alomare/flexible_loadouts
-- Flexible Loadouts by Alomare (formerly Flexible Stratagems, first released as Stratagems Unleashed).
--
-- Makes the stratagem slots of the Hellpod loadout easier to work with:
--   * ready with empty slots: the ready handler refuses while fewer slots are filled than min(owned, 4), flashing the
--     empty ones (slots marked disabled, as by a mission modifier, don't count). The game's update runs before the
--     mod's, so the mod sees the refusal and toggles the ready the handler's way: a flash starting, or, while a flash
--     still shows (the handler doesn't flash a slot again then), a Ready press told by the game's own press check.
--     Like the handler, it tells every peer to start (or stop) the ready pose;
--   * after a replacement in a full loadout (slot 1 to 3), the equip handler closes the list; the mod focuses the
--     next slot and opens the list again, as the handler does while slots are still empty, then focuses the
--     stratagem just picked and puts the list's scroll back where it was;
--   * Action (a Mod Bindings Menu key, for controllers too): empties the hovered or focused stratagem slot, flips the
--     hovered or focused weapon slot's Leave Out toggle, pins or unpins the hovered or focused stratagem in the list,
--     and on the booster slot randomizes the lineup. Slots are emptied through the slot widgets, then the loadout is
--     written and saved the way a pick does;
--   * clear buttons: a red X in the top-right corner of each filled stratagem slot of the local panel, made of the
--     game's own widgets as children of the slot (so the game places it), fading in and out with the game's own fade.
--     It shows only when the game would take a click on the slot (mouse mode). While the X is hovered the mod writes
--     the grid's hovered slot as none, so the game ignores the click there and the mod empties that slot the Clear
--     Stratagems way; the slot itself is shown unhovered the game's way;
--   * Leave Out: a REMOVE toggle at the top of the local panel's primary, secondary and grenade slots (the game's own
--     widgets, like the X's); in a mission the local Helldiver goes without what is left out, through the game's own weapon
--     selection, inventory and messages to teammates;
--   * pinned stratagems: a pin on the hovered or focused stratagem of the list; pinned ones come first in their
--     group (offensive, supply, defensive), reordered right after the game builds the list, kept across sessions;
--   * Randomize Lineup: a reroll button between the 4th stratagem slot and the booster fills the four slots, one at a
--     time, with one of three lineups drawn from the owned stratagems.
-- Game updates: every address and structure offset the mod uses is read from the game's own code, found by code
-- signatures (at this build's addresses first, else by a search of game.dll spread over a few frames). Anything not
-- found, found twice or inconsistent turns the mod off, and the loadout works as normal. The verdict is the first line of
-- %LOCALAPPDATA%\CowboyBingus\Helldivers2\Logs\FlexibleLoadouts_STATUS.log.
