-- The pins' code: the X's (widgets, fades, the click), the list scroll's (layout, focus), every list field found
-- and agreeing. Sets EXTRA.pins.
function pins.read()
    local why = (not EXTRA.buttons and ('needs the clear buttons: ' .. tostring(EXTRA.buttons_why)))
                or (not EXTRA.scroll and ('needs the list scroll code: ' .. tostring(EXTRA.scroll_why)))
                or H.missing_fields(H.PIN_FIELDS) or H.missing_fields({'grid_refresh', 'list_grid', 'mark'})
    for _, same in ipairs(H.PIN_SAME) do
        if not why and L[same[1]] ~= nil and L[same[1]] ~= L[same[2]] then
            why = string.format('"%s" differs from "%s"', same[1], same[2])
        end
    end
    -- The page cache is the array just before the group count (one entry a page); four cells a page.
    local pages = not why and (L.lg_count - L.lc_cache) / 4
    if not why and (pages ~= math.floor(pages) or pages < 1 or pages > 32) then why = 'list layout (page cache)' end
    if not why and L.lp_pad ~= L.mouse_mode + 1 then why = 'the pad byte is not right after the mouse byte' end
    -- Page 0's fields (from the list): its cells, its cell count and hovered column, all inside the first page.
    local function in_page(at, size) return at >= L.lc_page_base and at + size <= L.lc_page_base + L.lc_page_stride end
    if not why and (L.lc_offer + 4 > L.lc_cell_stride or L.lg_start <= L.lg_count
                    or not in_page(L.lc_cell0, H.PIN.columns * L.lc_cell_stride) or not in_page(L.lc_page_cells, 4)
                    or not in_page(L.lp_hover_col, 4)) then
        why = 'list layout (pages and cells)'
    end
    if not why then
        pins.pages = pages
        pins.fn = {}
        local casts = {preview = {'void (*)(uint64_t)', L.grid_refresh},
                       mark = {'void (*)(uint64_t, uint32_t, uint8_t)', L.mark}}
        for name, c in pairs(casts) do
            local ok, f = pcall(ffi.cast, c[1], native.base + c[2])
            if ok then pins.fn[name] = f else why = why or ('native function ' .. name .. ' unavailable') end
        end
    end
    EXTRA.pins, EXTRA.pins_why = not why, why
end

function H.pin_fail(why)
